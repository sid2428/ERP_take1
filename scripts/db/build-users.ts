/**
 * Builds data/generated/app_user.csv: one account per student and faculty member plus the admin.
 *
 *   * Students log in with their student number, faculty with their faculty code.
 *   * Initial password = date of birth (students) / date of joining (faculty) as DDMMYYYY,
 *     and must be changed at first login.
 *   * Demo accounts (one student, one faculty) use DEMO_PASSWORD; the admin uses ADMIN_PASSWORD.
 *     Missing values are generated and written to data/generated/demo-credentials.txt (gitignored).
 *
 * Usage: npm run data:users   (after npm run data:build; then npm run db:load)
 * Takes about 20 minutes: ~50k scrypt hashes on Node's 4-thread crypto pool. Run it once;
 * the resulting CSV is loaded into both the local and the Supabase database.
 */
import 'dotenv/config';
import { randomBytes } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { hashPassword, initialPassword } from '../../src/auth/password.js';
import { csvField, readCsv } from './csv.js';

const DIR = path.resolve(import.meta.dirname, '../../data/generated');
const DEMO_STUDENT = 'STU202600004';     // IT, year 3, semester V (as in the student mockup)

function secret(envName: string): { value: string; generated: boolean } {
  const fromEnv = process.env[envName];
  if (fromEnv && fromEnv.length >= 8) return { value: fromEnv, generated: false };
  return { value: `${randomBytes(9).toString('base64url')}7a`, generated: true };
}

async function mapLimit<T, R>(items: T[], limit: number, fn: (item: T) => Promise<R>): Promise<R[]> {
  const out = new Array<R>(items.length);
  let next = 0;
  let done = 0;
  async function worker(): Promise<void> {
    while (next < items.length) {
      const i = next++;
      out[i] = await fn(items[i] as T);
      if (++done % 5000 === 0) console.log(`  hashed ${done.toLocaleString()} / ${items.length.toLocaleString()}`);
    }
  }
  await Promise.all(Array.from({ length: limit }, worker));
  return out;
}

async function main(): Promise<void> {
  const started = Date.now();
  const [students, faculty, sections, assignments] = await Promise.all([
    readCsv(path.join(DIR, 'student.csv')), readCsv(path.join(DIR, 'faculty.csv')),
    readCsv(path.join(DIR, 'student_section.csv')), readCsv(path.join(DIR, 'teaching_assignment.csv')),
  ]);

  const demoStudent = students.find((s) => s.student_number === DEMO_STUDENT);
  if (!demoStudent) throw new Error(`demo student ${DEMO_STUDENT} not found`);
  const division = sections.find((s) => s.student_id === demoStudent.student_id)?.division_id;
  const demoFacultyId = assignments.find((a) => a.division_id === division && a.session_type === 'Lecture')?.faculty_id;
  const demoFaculty = faculty.find((f) => f.faculty_id === demoFacultyId);
  if (!demoFaculty) throw new Error('could not pick a demo faculty member');

  const demo = secret('DEMO_PASSWORD');
  const admin = secret('ADMIN_PASSWORD');

  type Account = { login: string; role: string; studentId: string; facultyId: string; password: string; mustChange: boolean };
  const accounts: Account[] = [
    { login: 'admin', role: 'admin', studentId: '', facultyId: '', password: admin.value, mustChange: false },
    ...faculty.map((f) => ({
      login: f.faculty_code as string, role: 'faculty', studentId: '', facultyId: f.faculty_id as string,
      password: f === demoFaculty ? demo.value : initialPassword(f.date_of_joining as string), mustChange: f !== demoFaculty,
    })),
    ...students.map((s) => ({
      login: s.student_number as string, role: 'student', studentId: s.student_id as string, facultyId: '',
      password: s === demoStudent ? demo.value : initialPassword(s.date_of_birth as string), mustChange: s !== demoStudent,
    })),
  ];

  console.log(`hashing ${accounts.length.toLocaleString()} passwords ...`);
  const hashes = await mapLimit(accounts, 16, (a) => hashPassword(a.password));

  const lines = ['user_id,login_id,role,student_id,faculty_id,password_hash,must_change_password'];
  accounts.forEach((a, i) => {
    lines.push([i + 1, a.login, a.role, a.studentId, a.facultyId, hashes[i], a.mustChange].map(csvField).join(','));
  });
  await writeFile(path.join(DIR, 'app_user.csv'), `${lines.join('\n')}\n`, 'utf8');

  const creds = [
    'Demo credentials (generated by npm run data:users; this file is gitignored)',
    `admin               password: ${admin.value}${admin.generated ? '   (generated; set ADMIN_PASSWORD in .env to choose)' : ''}`,
    `${demoStudent.student_number}        password: ${demo.value}   (student demo)`,
    `${demoFaculty.faculty_code}         password: ${demo.value}   (faculty demo)`,
    'All other accounts: initial password = date of birth / date of joining as DDMMYYYY (must be changed at first login).',
  ];
  await writeFile(path.join(DIR, 'demo-credentials.txt'), `${creds.join('\n')}\n`, 'utf8');
  console.log(`wrote app_user.csv (${accounts.length.toLocaleString()} accounts) in ${((Date.now() - started) / 1000).toFixed(0)} s`);
  console.log(`demo accounts: ${demoStudent.student_number}, ${demoFaculty.faculty_code}, admin -> see data/generated/demo-credentials.txt`);
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
