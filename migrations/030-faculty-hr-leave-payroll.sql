CREATE TABLE IF NOT EXISTS salary_structure (
    salary_structure_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id              INT NOT NULL REFERENCES faculty(faculty_id),
    basic_salary            NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (basic_salary >= 0),
    allowances              NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (allowances >= 0),
    deductions              NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (deductions >= 0),
    leave_deduction_per_day NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (leave_deduction_per_day >= 0),
    effective_from          DATE NOT NULL,
    effective_to            DATE NULL CHECK (effective_to IS NULL OR effective_to >= effective_from),
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chk_salary_deductions_limit CHECK (deductions <= basic_salary + allowances),
    CONSTRAINT ex_salary_structure_no_overlap
        EXCLUDE USING gist (faculty_id WITH =, daterange(effective_from, effective_to, '[]') WITH &&)
);
CREATE INDEX IF NOT EXISTS idx_salary_structure_faculty_date ON salary_structure (faculty_id, effective_from, effective_to);

CREATE TABLE IF NOT EXISTS payroll (
    payroll_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id          INT NOT NULL REFERENCES faculty(faculty_id),
    payroll_month       SMALLINT NOT NULL CHECK (payroll_month BETWEEN 1 AND 12),
    payroll_year        SMALLINT NOT NULL CHECK (payroll_year >= 2000),
    basic_salary        NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (basic_salary >= 0),
    allowances          NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (allowances >= 0),
    deductions          NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (deductions >= 0),
    leave_deductions    NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (leave_deductions >= 0),
    net_salary          NUMERIC(12,2) NOT NULL CHECK (net_salary >= 0),
    status              payroll_status NOT NULL DEFAULT 'DRAFT',
    generated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    salary_structure_id INT NULL REFERENCES salary_structure(salary_structure_id),
    approved_by         INT NULL REFERENCES app_user(user_id),
    approved_at         TIMESTAMPTZ NULL,
    paid_at             TIMESTAMPTZ NULL,

    CONSTRAINT uq_payroll_faculty_month UNIQUE (faculty_id, payroll_month, payroll_year),
    CONSTRAINT chk_payroll_net_formula CHECK (
        net_salary = basic_salary + allowances - deductions - leave_deductions)
);

CREATE TABLE IF NOT EXISTS payroll_item (
    payroll_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payroll_id      BIGINT NOT NULL REFERENCES payroll(payroll_id) ON DELETE CASCADE,
    component_name  VARCHAR(100) NOT NULL,
    component_type  payroll_component_type NOT NULL,
    amount          NUMERIC(12,2) NOT NULL CHECK (amount >= 0),

    CONSTRAINT uq_payroll_item_component UNIQUE (payroll_id, component_name)
);

