CREATE TABLE IF NOT EXISTS faculty_leave_type (
    leave_type_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leave_name    VARCHAR(100) NOT NULL UNIQUE,
    annual_quota  NUMERIC(5,2) NOT NULL CHECK (annual_quota >= 0),
    is_paid       BOOLEAN NOT NULL DEFAULT TRUE,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS faculty_leave_request (
    leave_request_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id       INT NOT NULL REFERENCES faculty(faculty_id),
    leave_type_id    INT NOT NULL REFERENCES faculty_leave_type(leave_type_id),
    from_date        DATE NOT NULL,
    to_date          DATE NOT NULL,
    days_requested   NUMERIC(5,2) NOT NULL CHECK (days_requested > 0),
    reason           VARCHAR(500),
    status           leave_status NOT NULL DEFAULT 'PENDING',
    approved_by      INT NULL REFERENCES app_user(user_id),
    approved_at      TIMESTAMPTZ NULL,
    decision_remarks VARCHAR(255) NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chk_leave_request_dates CHECK (to_date >= from_date),
    CONSTRAINT chk_leave_request_days_range
        CHECK (days_requested <= (to_date - from_date) + 1),
    CONSTRAINT chk_leave_request_single_year
        CHECK (EXTRACT(YEAR FROM from_date) = EXTRACT(YEAR FROM to_date)),
    CONSTRAINT chk_leave_request_decision
        CHECK (status NOT IN ('APPROVED', 'REJECTED') OR approved_by IS NOT NULL),

    CONSTRAINT ex_leave_request_no_overlap
        EXCLUDE USING gist (faculty_id WITH =, daterange(from_date, to_date, '[]') WITH &&)
        WHERE (status IN ('PENDING', 'APPROVED'))
);
CREATE INDEX IF NOT EXISTS idx_leave_request_faculty ON faculty_leave_request (faculty_id);
CREATE INDEX IF NOT EXISTS idx_leave_request_status  ON faculty_leave_request (status);
CREATE INDEX IF NOT EXISTS idx_leave_request_date    ON faculty_leave_request (from_date, to_date);

CREATE TABLE IF NOT EXISTS faculty_leave_transaction (
    transaction_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id       INT NOT NULL REFERENCES faculty(faculty_id),
    leave_type_id    INT NOT NULL REFERENCES faculty_leave_type(leave_type_id),
    leave_request_id INT NULL REFERENCES faculty_leave_request(leave_request_id),
    days_delta       NUMERIC(5,2) NOT NULL CHECK (days_delta <> 0),
    transaction_date DATE NOT NULL,
    remarks          VARCHAR(255),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),

    delta_sign SMALLINT GENERATED ALWAYS AS (sign(days_delta)::smallint) STORED,

    CONSTRAINT uq_leave_transaction_request_sign UNIQUE (leave_request_id, delta_sign)
);
CREATE INDEX IF NOT EXISTS idx_leave_transaction_faculty_type ON faculty_leave_transaction (faculty_id, leave_type_id);
CREATE INDEX IF NOT EXISTS idx_leave_transaction_date         ON faculty_leave_transaction (transaction_date);

CREATE OR REPLACE FUNCTION get_faculty_leave_balance_for_year(
    p_faculty_id INT, p_leave_type_id INT, p_year INT)
RETURNS NUMERIC
LANGUAGE plpgsql STABLE SET search_path = erp, public AS $$
DECLARE
    v_quota NUMERIC;
    v_net   NUMERIC;
BEGIN
    SELECT annual_quota INTO v_quota FROM faculty_leave_type WHERE leave_type_id = p_leave_type_id;
    IF v_quota IS NULL THEN
        RETURN NULL;
    END IF;

    SELECT COALESCE(SUM(days_delta), 0) INTO v_net
      FROM faculty_leave_transaction
     WHERE faculty_id    = p_faculty_id
       AND leave_type_id = p_leave_type_id
       AND transaction_date >= make_date(p_year, 1, 1)
       AND transaction_date <  make_date(p_year + 1, 1, 1);

    RETURN v_quota + v_net;
END $$;

CREATE OR REPLACE FUNCTION get_faculty_leave_balance(p_faculty_id INT, p_leave_type_id INT)
RETURNS NUMERIC
LANGUAGE sql STABLE SET search_path = erp, public AS $$
    SELECT get_faculty_leave_balance_for_year(
        p_faculty_id, p_leave_type_id, EXTRACT(YEAR FROM CURRENT_DATE)::INT);
$$;

CREATE OR REPLACE FUNCTION fn_leave_request_before_insert() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
    v_f_status employment_status;
    v_joining  DATE;
    v_t_active BOOLEAN;
BEGIN
    IF NEW.status <> 'PENDING' THEN
        RAISE EXCEPTION 'New leave requests must start as PENDING';
    END IF;

    SELECT status, date_of_joining INTO v_f_status, v_joining
      FROM faculty WHERE faculty_id = NEW.faculty_id;
    IF v_f_status IS DISTINCT FROM 'Active' THEN
        RAISE EXCEPTION 'Faculty member is inactive';
    END IF;

    SELECT is_active INTO v_t_active FROM faculty_leave_type WHERE leave_type_id = NEW.leave_type_id;
    IF v_t_active IS NOT TRUE THEN
        RAISE EXCEPTION 'Leave type is inactive';
    END IF;

    IF NEW.from_date < v_joining THEN
        RAISE EXCEPTION 'Leave cannot start before the joining date';
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_leave_request_before_insert ON faculty_leave_request;
CREATE TRIGGER trg_leave_request_before_insert BEFORE INSERT ON faculty_leave_request
    FOR EACH ROW EXECUTE FUNCTION fn_leave_request_before_insert();

CREATE OR REPLACE FUNCTION fn_leave_request_before_update() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
    v_role    user_role;
    v_active  BOOLEAN;
    v_paid    BOOLEAN;
    v_balance NUMERIC;
BEGIN
    IF OLD.status <> 'PENDING' AND (
           NEW.faculty_id     IS DISTINCT FROM OLD.faculty_id
        OR NEW.leave_type_id  IS DISTINCT FROM OLD.leave_type_id
        OR NEW.from_date      IS DISTINCT FROM OLD.from_date
        OR NEW.to_date        IS DISTINCT FROM OLD.to_date
        OR NEW.days_requested IS DISTINCT FROM OLD.days_requested) THEN
        RAISE EXCEPTION 'Faculty, leave type, dates and days cannot be changed after a decision';
    END IF;

    IF NEW.status <> OLD.status THEN
        IF NOT ( (OLD.status = 'PENDING'  AND NEW.status IN ('APPROVED', 'REJECTED', 'CANCELLED'))
              OR (OLD.status = 'APPROVED' AND NEW.status = 'CANCELLED') ) THEN
            RAISE EXCEPTION 'Invalid leave status transition';
        END IF;

        IF NEW.status IN ('APPROVED', 'REJECTED') THEN
            IF NEW.approved_by IS NULL THEN
                RAISE EXCEPTION 'approved_by is required for a decision';
            END IF;
            SELECT role, is_active INTO v_role, v_active FROM app_user WHERE user_id = NEW.approved_by;
            IF v_role IS NULL OR v_role <> 'admin' OR v_active IS NOT TRUE THEN
                RAISE EXCEPTION 'Approver must be an active administrator';
            END IF;
            NEW.approved_at := COALESCE(NEW.approved_at, now());
        END IF;

        IF NEW.status = 'APPROVED' THEN
            SELECT is_paid INTO v_paid FROM faculty_leave_type WHERE leave_type_id = NEW.leave_type_id;
            IF v_paid THEN
                v_balance := get_faculty_leave_balance_for_year(
                                 NEW.faculty_id, NEW.leave_type_id, EXTRACT(YEAR FROM NEW.from_date)::INT);
                IF v_balance < NEW.days_requested THEN
                    RAISE EXCEPTION 'Insufficient leave balance';
                END IF;
            END IF;
        END IF;
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_leave_request_before_update ON faculty_leave_request;
CREATE TRIGGER trg_leave_request_before_update BEFORE UPDATE ON faculty_leave_request
    FOR EACH ROW EXECUTE FUNCTION fn_leave_request_before_update();

CREATE OR REPLACE FUNCTION fn_after_faculty_leave_approval() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
    IF OLD.status = 'PENDING' AND NEW.status = 'APPROVED' THEN
        INSERT INTO faculty_leave_transaction
            (faculty_id, leave_request_id, leave_type_id, transaction_date, days_delta, remarks)
        VALUES
            (NEW.faculty_id, NEW.leave_request_id, NEW.leave_type_id,
             NEW.from_date, -NEW.days_requested, 'Leave approved');
    ELSIF OLD.status = 'APPROVED' AND NEW.status = 'CANCELLED' THEN
        INSERT INTO faculty_leave_transaction
            (faculty_id, leave_request_id, leave_type_id, transaction_date, days_delta, remarks)
        VALUES
            (NEW.faculty_id, NEW.leave_request_id, NEW.leave_type_id,
             NEW.from_date, NEW.days_requested, 'Approved leave cancelled - balance restored');
    END IF;
    RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS trg_after_faculty_leave_approval ON faculty_leave_request;
CREATE TRIGGER trg_after_faculty_leave_approval AFTER UPDATE ON faculty_leave_request
    FOR EACH ROW EXECUTE FUNCTION fn_after_faculty_leave_approval();

CREATE OR REPLACE PROCEDURE approve_faculty_leave(p_leave_request_id INT, p_approved_by INT)
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE v_rows INT;
BEGIN
    UPDATE faculty_leave_request
       SET status = 'APPROVED', approved_by = p_approved_by
     WHERE leave_request_id = p_leave_request_id AND status = 'PENDING';
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    IF v_rows = 0 THEN
        RAISE EXCEPTION 'Invalid request or request is not pending';
    END IF;
END $$;

CREATE OR REPLACE PROCEDURE reject_faculty_leave(p_leave_request_id INT, p_rejected_by INT, p_remarks VARCHAR)
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE v_rows INT;
BEGIN
    UPDATE faculty_leave_request
       SET status = 'REJECTED', approved_by = p_rejected_by, decision_remarks = p_remarks
     WHERE leave_request_id = p_leave_request_id AND status = 'PENDING';
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    IF v_rows = 0 THEN
        RAISE EXCEPTION 'Invalid request or request is not pending';
    END IF;
END $$;

CREATE OR REPLACE PROCEDURE cancel_faculty_leave(p_leave_request_id INT, p_remarks VARCHAR)
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE v_rows INT;
BEGIN
    UPDATE faculty_leave_request
       SET status = 'CANCELLED', decision_remarks = p_remarks
     WHERE leave_request_id = p_leave_request_id AND status IN ('PENDING', 'APPROVED');
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    IF v_rows = 0 THEN
        RAISE EXCEPTION 'Invalid request or request is already rejected/cancelled';
    END IF;
END $$;

