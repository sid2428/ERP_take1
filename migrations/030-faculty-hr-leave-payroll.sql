-- Seed baseline salary structures for faculty members using G6 / T2 conventions:
-- Professor: Basic 90k, DA+HRA 54k (60%), PF+PT 11k (12%+200)
-- Associate: Basic 70k, DA+HRA 42k (60%), PF+PT 8.6k
-- Assistant: Basic 50k, DA+HRA 30k (60%), PF+PT 6.2k
INSERT INTO salary_structure (faculty_id, basic_salary, allowances, deductions, leave_deduction_per_day, effective_from)
SELECT
    f.faculty_id,
    CASE f.designation
        WHEN 'Professor' THEN 90000.00
        WHEN 'Associate Professor' THEN 70000.00
        ELSE 50000.00
    END AS basic_salary,
    CASE f.designation
        WHEN 'Professor' THEN 54000.00
        WHEN 'Associate Professor' THEN 42000.00
        ELSE 30000.00
    END AS allowances,
    CASE f.designation
        WHEN 'Professor' THEN 11000.00
        WHEN 'Associate Professor' THEN 8600.00
        ELSE 6200.00
    END AS deductions,
    CASE f.designation
        WHEN 'Professor' THEN 4800.00
        WHEN 'Associate Professor' THEN 3733.00
        ELSE 2667.00
    END AS leave_deduction_per_day,
    '2026-01-01'::DATE AS effective_from
FROM faculty f
WHERE NOT EXISTS (
    SELECT 1 FROM salary_structure s WHERE s.faculty_id = f.faculty_id
);
