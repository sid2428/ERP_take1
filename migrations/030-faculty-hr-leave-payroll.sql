LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
    IF NEW.status <> 'DRAFT' THEN
        RAISE EXCEPTION 'Payroll must be created as DRAFT';
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_payroll_before_insert ON payroll;
CREATE TRIGGER trg_payroll_before_insert BEFORE INSERT ON payroll
    FOR EACH ROW EXECUTE FUNCTION fn_payroll_before_insert();

CREATE OR REPLACE FUNCTION fn_payroll_before_update() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
    v_role user_role;
BEGIN
    IF OLD.status <> 'DRAFT' AND (
           NEW.faculty_id       IS DISTINCT FROM OLD.faculty_id
        OR NEW.payroll_month    IS DISTINCT FROM OLD.payroll_month
        OR NEW.payroll_year     IS DISTINCT FROM OLD.payroll_year
        OR NEW.basic_salary     IS DISTINCT FROM OLD.basic_salary
        OR NEW.allowances       IS DISTINCT FROM OLD.allowances
        OR NEW.deductions       IS DISTINCT FROM OLD.deductions
        OR NEW.leave_deductions IS DISTINCT FROM OLD.leave_deductions
        OR NEW.net_salary       IS DISTINCT FROM OLD.net_salary) THEN
        RAISE EXCEPTION 'Approved/Paid payroll cannot be modified';
    END IF;

    IF NEW.status <> OLD.status THEN
        IF NOT ( (OLD.status = 'DRAFT'    AND NEW.status = 'APPROVED')
              OR (OLD.status = 'APPROVED' AND NEW.status = 'PAID') ) THEN
            RAISE EXCEPTION 'Invalid payroll status transition (DRAFT -> APPROVED -> PAID only)';
        END IF;

        IF NEW.status = 'APPROVED' THEN
            IF NEW.approved_by IS NULL THEN
                RAISE EXCEPTION 'approved_by is required to approve payroll';
            END IF;
            SELECT role INTO v_role FROM app_user WHERE user_id = NEW.approved_by AND is_active;
            IF v_role IS NULL OR v_role <> 'admin' THEN
                RAISE EXCEPTION 'Payroll approver must be an active administrator';
            END IF;
            NEW.approved_at := now();
        END IF;

        IF NEW.status = 'PAID' THEN
            NEW.paid_at := now();
        END IF;
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_payroll_before_update ON payroll;
CREATE TRIGGER trg_payroll_before_update BEFORE UPDATE ON payroll
    FOR EACH ROW EXECUTE FUNCTION fn_payroll_before_update();

