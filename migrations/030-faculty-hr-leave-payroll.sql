CREATE OR REPLACE VIEW v_faculty_leave_balance_current_year AS
SELECT  f.faculty_id,
        f.faculty_code,
        concat_ws(' ', f.first_name, f.last_name) AS faculty_name,
        lt.leave_type_id,
        lt.leave_name,
        lt.is_paid,
        EXTRACT(YEAR FROM CURRENT_DATE)::INT      AS balance_year,
        lt.annual_quota,
        get_faculty_leave_balance_for_year(
            f.faculty_id, lt.leave_type_id, EXTRACT(YEAR FROM CURRENT_DATE)::INT) AS balance_days
FROM faculty f
CROSS JOIN faculty_leave_type lt
WHERE f.status = 'Active' AND lt.is_active;

CREATE OR REPLACE VIEW v_faculty_leave_balance AS
SELECT faculty_id, leave_name AS leave_type, balance_days AS remaining
FROM v_faculty_leave_balance_current_year;

