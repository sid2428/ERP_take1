-- 083 · T8 dedicated personal notifications.
-- Announcements remain in notice/notice_target. Personal event messages move to this table,
-- while v_user_notices exposes both kinds with an explicit item_type discriminator.
-- Depends on: 007 (app_user), 080 (grievances), 081 (notice), 082 (personal notice metadata).
SET search_path = erp, public;

CREATE TABLE notification (
  notification_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         int          NOT NULL REFERENCES app_user ON DELETE CASCADE,
  kind            varchar(20)  NOT NULL CHECK (length(btrim(kind)) BETWEEN 1 AND 20),
  title           varchar(150) NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 150),
  text            text         NOT NULL CHECK (length(btrim(text)) BETWEEN 1 AND 5000),
  category        notice_category NOT NULL DEFAULT 'General',
  link            varchar(200) CHECK (link IS NULL OR link ~ '^/[A-Za-z0-9/_?=&.-]*$'),
  created_at      timestamptz  NOT NULL DEFAULT now(),
  expires_at      timestamptz,
  read_at         timestamptz,
  posted_by       int          REFERENCES app_user ON DELETE SET NULL,
  legacy_notice_id int         REFERENCES notice ON DELETE SET NULL,
  CHECK (expires_at IS NULL OR expires_at > created_at),
  UNIQUE (legacy_notice_id, user_id)
);
CREATE INDEX notification_user_created_idx ON notification (user_id, created_at DESC, notification_id DESC);
CREATE INDEX notification_unread_idx ON notification (user_id, notification_id) WHERE read_at IS NULL;
CREATE INDEX notification_legacy_notice_idx ON notification (legacy_notice_id) WHERE legacy_notice_id IS NOT NULL;

GRANT SELECT, INSERT, UPDATE, DELETE ON notification TO erp_app;
GRANT USAGE, SELECT ON SEQUENCE notification_notification_id_seq TO erp_app;

-- Backfill only notices whose complete audience is personal. A mixed group/personal notice stays
-- in notice so its group audience cannot be lost or shown twice.
INSERT INTO notification (user_id, kind, title, text, category, link, created_at, expires_at, read_at,
                          posted_by, legacy_notice_id)
SELECT t.user_id,
       left(COALESCE(n.source, 'legacy'), 20),
       n.title,
       n.body,
       n.category,
       n.link,
       n.posted_at,
       n.expires_at,
       r.read_at,
       n.posted_by,
       n.notice_id
FROM notice n
JOIN notice_target t ON t.notice_id = n.notice_id AND t.user_id IS NOT NULL
LEFT JOIN notice_read r ON r.notice_id = n.notice_id AND r.user_id = t.user_id
WHERE NOT EXISTS (
        SELECT 1 FROM notice_target group_target
        WHERE group_target.notice_id = n.notice_id AND group_target.user_id IS NULL
      );

-- Internal insertion helper used by both the required procedure and the compatibility adapter.
CREATE FUNCTION _insert_notification(
  p_user_id int, p_kind text, p_title text, p_text text, p_category notice_category,
  p_link text, p_expires_at timestamptz, p_posted_by int DEFAULT NULL,
  p_read_at timestamptz DEFAULT NULL, p_legacy_notice_id int DEFAULT NULL
) RETURNS int
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  v_id int;
BEGIN
  IF p_user_id IS NULL OR NOT EXISTS (
    SELECT 1 FROM app_user WHERE user_id = p_user_id AND is_active
  ) THEN
    RETURN NULL;
  END IF;
  INSERT INTO notification (user_id, kind, title, text, category, link, expires_at, posted_by, read_at, legacy_notice_id)
  VALUES (p_user_id, p_kind, btrim(p_title), btrim(p_text), p_category, p_link, p_expires_at, p_posted_by, p_read_at,
          p_legacy_notice_id)
  RETURNING notification_id INTO v_id;
  RETURN v_id;
END $$;

-- Required assignment contract. A first line in p_text is used as the display title when it is
-- no longer than 150 characters; the complete message remains in notification.text.
CREATE PROCEDURE notify(p_user_id int, p_kind text, p_text text, p_link text)
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  CALL notify(p_user_id, p_kind, p_text, p_link, 'General');
END $$;

-- The category overload preserves the existing grievance category filters while the required
-- four-argument contract remains available to every team.
CREATE PROCEDURE notify(p_user_id int, p_kind text, p_text text, p_link text, p_category notice_category)
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  v_title text;
BEGIN
  IF p_user_id IS NULL OR NOT EXISTS (SELECT 1 FROM app_user WHERE user_id = p_user_id AND is_active) THEN
    RETURN;
  END IF;
  IF p_kind IS NULL OR length(btrim(p_kind)) NOT BETWEEN 1 AND 20 THEN
    RAISE EXCEPTION 'notification kind must contain 1 to 20 characters' USING ERRCODE = 'check_violation';
  END IF;
  IF p_text IS NULL OR length(btrim(p_text)) NOT BETWEEN 1 AND 5000 THEN
    RAISE EXCEPTION 'notification text must contain 1 to 5000 characters' USING ERRCODE = 'check_violation';
  END IF;
  IF p_link IS NOT NULL AND p_link !~ '^/[A-Za-z0-9/_?=&.-]*$' THEN
    RAISE EXCEPTION 'notification links must be internal portal paths' USING ERRCODE = 'check_violation';
  END IF;
  v_title := CASE
    WHEN strpos(p_text, E'\n') BETWEEN 2 AND 151 THEN split_part(p_text, E'\n', 1)
    ELSE initcap(replace(p_kind, '_', ' '))
  END;
  PERFORM _insert_notification(p_user_id, btrim(p_kind), v_title, p_text, p_category, p_link, now() + interval '60 days');
END $$;

-- Backward-compatible adapter for existing callers. New event triggers use notify(...); this
-- function retains the old return value, title/body, category, expiry and source semantics.
CREATE OR REPLACE FUNCTION notify_user(p_user_id int, p_title text, p_body text, p_category notice_category,
                                       p_link text DEFAULT NULL, p_source text DEFAULT NULL)
RETURNS int
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  RETURN _insert_notification(p_user_id, left(COALESCE(p_source, 'system'), 20), p_title, p_body, p_category,
                              p_link, now() + interval '60 days');
END $$;

-- Combined inbox contract. The first 16 columns preserve the 082 shape; the appended columns
-- prevent notice IDs and notification IDs from being confused by routes or clients.
CREATE OR REPLACE VIEW v_user_notices AS
SELECT a.user_id, n.notice_id, n.title, n.body, n.category, n.is_important, n.posted_at, n.expires_at,
       n.posted_by, COALESCE(pp.display_name, 'Academic office') AS posted_by_name, pp.role AS posted_by_role,
       r.read_at, r.read_at IS NOT NULL AS is_read,
       n.link, n.source, EXISTS (SELECT 1 FROM notice_target t WHERE t.notice_id = n.notice_id AND t.user_id IS NOT NULL) AS is_personal,
       'notice'::text AS item_type, NULL::int AS notification_id, NULL::varchar(20) AS notification_kind
FROM v_user_audience a
JOIN notice n ON n.withdrawn_at IS NULL AND (n.expires_at IS NULL OR n.expires_at > now())
             AND EXISTS (SELECT 1 FROM notice_target t WHERE t.notice_id = n.notice_id AND notice_target_matches(t, a))
             AND (EXISTS (SELECT 1 FROM notice_target t WHERE t.notice_id = n.notice_id AND t.user_id IS NULL)
                  OR NOT EXISTS (SELECT 1 FROM notice_target t WHERE t.notice_id = n.notice_id AND t.user_id IS NOT NULL))
LEFT JOIN v_user_profile pp ON pp.user_id = n.posted_by
LEFT JOIN notice_read r ON r.notice_id = n.notice_id AND r.user_id = a.user_id
UNION ALL
SELECT a.user_id, NULL::int AS notice_id, x.title,
       CASE WHEN strpos(x.text, E'\n') > 0 AND left(x.text, length(x.title) + 1) = x.title || E'\n'
            THEN substring(x.text FROM length(x.title) + 2) ELSE x.text END AS body,
       x.category, false AS is_important, x.created_at AS posted_at, x.expires_at,
       x.posted_by, COALESCE(pp.display_name, 'Academic office') AS posted_by_name, pp.role AS posted_by_role,
       x.read_at, x.read_at IS NOT NULL AS is_read,
       x.link, x.kind::varchar(20) AS source, true AS is_personal,
       'notification'::text AS item_type, x.notification_id, x.kind::varchar(20) AS notification_kind
FROM v_user_audience a
JOIN notification x ON x.user_id = a.user_id AND (x.expires_at IS NULL OR x.expires_at > now())
LEFT JOIN v_user_profile pp ON pp.user_id = x.posted_by;

