-- 080 · T8-2 Grievances.
-- Flow: a student or faculty member raises a grievance (Open) -> the admin may assign it to a faculty
-- member, which moves it to In progress -> raiser, admin and assignee discuss it in the comment
-- trail -> the admin closes it as Resolved (approved) or Rejected, always with a note.
-- Closed grievances are frozen. Every status change is logged by a trigger.
-- Depends on: 003 (faculty), 007 (app_user, user_role, v_user_profile).
-- The app tells the triggers who is acting with set_config('erp.user_id', <user_id>, true).
SET search_path = erp, public;

CREATE TYPE grievance_category AS ENUM ('Academic', 'Attendance', 'Fees', 'Exam', 'Facilities', 'Other');
CREATE TYPE grievance_status   AS ENUM ('Open', 'In progress', 'Resolved', 'Rejected');

-- Lets the composite FK below prove the raiser's stored role is their real role.
ALTER TABLE app_user ADD CONSTRAINT app_user_id_role_key UNIQUE (user_id, role);

CREATE TABLE grievance (
  grievance_id    int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raised_by       int          NOT NULL,
  raised_by_role  user_role    NOT NULL CHECK (raised_by_role IN ('student', 'faculty')),   -- admins don't raise
  category        grievance_category NOT NULL,
  subject         varchar(120) NOT NULL CHECK (length(btrim(subject)) >= 5),
  description     text         NOT NULL CHECK (length(btrim(description)) BETWEEN 10 AND 4000),
  status          grievance_status NOT NULL DEFAULT 'Open',
  assigned_to     int          REFERENCES faculty,
  assigned_at     timestamptz,
  resolution_note text         CHECK (length(resolution_note) <= 2000),
  resolved_by     int          REFERENCES app_user,                 -- the admin who closed it
  created_at      timestamptz  NOT NULL DEFAULT now(),
  updated_at      timestamptz  NOT NULL DEFAULT now(),
  resolved_at     timestamptz,
  FOREIGN KEY (raised_by, raised_by_role) REFERENCES app_user (user_id, role),
  CHECK ((assigned_to IS NULL) = (assigned_at IS NULL)),
  -- closed <=> stamped; a closed grievance always explains its outcome
  CHECK ((status IN ('Resolved', 'Rejected')) = (resolved_at IS NOT NULL)),
  CHECK (status NOT IN ('Resolved', 'Rejected') OR length(btrim(COALESCE(resolution_note, ''))) >= 5),
  CHECK (resolved_at IS NULL OR resolved_at >= created_at)
);
CREATE INDEX ON grievance (raised_by);
CREATE INDEX ON grievance (assigned_to);
CREATE INDEX ON grievance (status, created_at DESC);

CREATE TABLE grievance_comment (
  comment_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  grievance_id int          NOT NULL REFERENCES grievance ON DELETE CASCADE,
  author_id    int          NOT NULL REFERENCES app_user,
  body         text         NOT NULL CHECK (length(btrim(body)) BETWEEN 1 AND 2000),
  created_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ON grievance_comment (grievance_id, created_at);

-- One row per status change (including the initial Open), written only by the trigger below.
CREATE TABLE grievance_status_log (
  log_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  grievance_id int              NOT NULL REFERENCES grievance ON DELETE CASCADE,
  from_status  grievance_status,
  to_status    grievance_status NOT NULL,
  changed_by   int              REFERENCES app_user ON DELETE SET NULL,
  changed_at   timestamptz      NOT NULL DEFAULT now(),
  CHECK (from_status IS DISTINCT FROM to_status)
);
CREATE INDEX ON grievance_status_log (grievance_id, changed_at);

-- ---------------------------------------------------------------------------------------
-- Who is acting (set by the app per transaction); NULL for maintenance scripts.
CREATE FUNCTION acting_user_id() RETURNS int
LANGUAGE sql STABLE AS $$
  SELECT NULLIF(current_setting('erp.user_id', true), '')::int
$$;

-- May this account read and comment on this grievance? Admins, the raiser and the assignee.
CREATE FUNCTION grievance_participant(p_user_id int, p_grievance_id int) RETURNS boolean
LANGUAGE sql STABLE SET search_path = erp, public AS $$
  SELECT EXISTS (
    SELECT 1 FROM grievance g JOIN app_user u ON u.user_id = p_user_id
    WHERE g.grievance_id = p_grievance_id
      AND (u.role = 'admin' OR g.raised_by = u.user_id OR (g.assigned_to IS NOT NULL AND g.assigned_to = u.faculty_id)))
$$;

-- New grievances always start Open, unassigned and unresolved.
CREATE FUNCTION trg_grievance_insert() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  IF NEW.status <> 'Open' OR NEW.assigned_to IS NOT NULL OR NEW.resolved_at IS NOT NULL OR NEW.resolved_by IS NOT NULL THEN
    RAISE EXCEPTION 'a new grievance must be Open and unassigned' USING ERRCODE = 'check_violation';
  END IF;
  NEW.updated_at := NEW.created_at;
  RETURN NEW;
END $$;
CREATE TRIGGER new_grievance BEFORE INSERT ON grievance
  FOR EACH ROW EXECUTE FUNCTION trg_grievance_insert();

-- Workflow rules: allowed transitions, frozen fields, assignment and resolution stamps.
CREATE FUNCTION trg_grievance_workflow() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  v_closed boolean := OLD.status IN ('Resolved', 'Rejected');
  v_assignee_user int;
BEGIN
  IF v_closed THEN
    RAISE EXCEPTION 'grievance % is already %; it cannot be changed', OLD.grievance_id, lower(OLD.status::text)
      USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.raised_by <> OLD.raised_by OR NEW.raised_by_role <> OLD.raised_by_role OR NEW.subject <> OLD.subject
     OR NEW.description <> OLD.description OR NEW.created_at <> OLD.created_at THEN
    RAISE EXCEPTION 'who raised a grievance and what they wrote cannot be changed' USING ERRCODE = 'check_violation';
  END IF;

  -- Open -> In progress | Resolved | Rejected;  In progress -> Resolved | Rejected
  IF NEW.status <> OLD.status AND NOT (
       (OLD.status = 'Open' AND NEW.status IN ('In progress', 'Resolved', 'Rejected'))
    OR (OLD.status = 'In progress' AND NEW.status IN ('Resolved', 'Rejected'))) THEN
    RAISE EXCEPTION 'a grievance cannot go from % to %', OLD.status, NEW.status USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.assigned_to IS DISTINCT FROM OLD.assigned_to THEN
    IF NEW.assigned_to IS NULL THEN
      NEW.assigned_at := NULL;
    ELSE
      IF NOT EXISTS (SELECT 1 FROM faculty WHERE faculty_id = NEW.assigned_to AND status = 'Active') THEN
        RAISE EXCEPTION 'grievances can only be assigned to active faculty' USING ERRCODE = 'check_violation';
      END IF;
      SELECT user_id INTO v_assignee_user FROM app_user WHERE faculty_id = NEW.assigned_to;
      IF v_assignee_user = NEW.raised_by THEN
        RAISE EXCEPTION 'a grievance cannot be assigned to the person who raised it' USING ERRCODE = 'check_violation';
      END IF;
      IF NEW.assigned_at IS NOT DISTINCT FROM OLD.assigned_at THEN NEW.assigned_at := now(); END IF;
      IF NEW.status = 'Open' THEN NEW.status := 'In progress'; END IF;    -- assigning starts the work
    END IF;
  END IF;

  IF NEW.status IN ('Resolved', 'Rejected') THEN
    NEW.resolved_at := COALESCE(NEW.resolved_at, now());
    NEW.resolved_by := COALESCE(NEW.resolved_by, acting_user_id());
    IF NOT EXISTS (SELECT 1 FROM app_user WHERE user_id = NEW.resolved_by AND role = 'admin') THEN
      RAISE EXCEPTION 'only an admin can close a grievance' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.resolved_at IS NOT NULL OR NEW.resolved_by IS NOT NULL THEN
    RAISE EXCEPTION 'only a closed grievance has a resolution' USING ERRCODE = 'check_violation';
  END IF;

  NEW.updated_at := GREATEST(now(), NEW.resolved_at, NEW.assigned_at);
  RETURN NEW;
END $$;
CREATE TRIGGER workflow BEFORE UPDATE ON grievance
  FOR EACH ROW EXECUTE FUNCTION trg_grievance_workflow();

CREATE FUNCTION trg_grievance_log_status() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO grievance_status_log (grievance_id, from_status, to_status, changed_by, changed_at)
    VALUES (NEW.grievance_id, NULL, NEW.status, NEW.raised_by, NEW.created_at);
  ELSIF NEW.status <> OLD.status THEN
    INSERT INTO grievance_status_log (grievance_id, from_status, to_status, changed_by, changed_at)
    VALUES (NEW.grievance_id, OLD.status, NEW.status, COALESCE(acting_user_id(), NEW.resolved_by), NEW.updated_at);
  END IF;
  RETURN NULL;
END $$;
-- not UPDATE OF status: the workflow trigger itself may change the status (assignment)
CREATE TRIGGER log_status AFTER INSERT OR UPDATE ON grievance
  FOR EACH ROW EXECUTE FUNCTION trg_grievance_log_status();

-- Comments: only participants, only while the grievance is not closed.
CREATE FUNCTION trg_grievance_comment_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  v_status grievance_status;
BEGIN
  SELECT status INTO v_status FROM grievance WHERE grievance_id = NEW.grievance_id;
  IF v_status IN ('Resolved', 'Rejected') THEN
    RAISE EXCEPTION 'grievance % is closed; no more comments', NEW.grievance_id USING ERRCODE = 'check_violation';
  END IF;
  IF NOT grievance_participant(NEW.author_id, NEW.grievance_id) THEN
    RAISE EXCEPTION 'only the raiser, the assigned faculty member or an admin can comment' USING ERRCODE = 'check_violation';
  END IF;
  -- any reply bumps the grievance's last activity (status stays as it is)
  UPDATE grievance SET updated_at = GREATEST(updated_at, NEW.created_at) WHERE grievance_id = NEW.grievance_id;
  RETURN NEW;
END $$;
CREATE TRIGGER participant_only BEFORE INSERT ON grievance_comment
  FOR EACH ROW EXECUTE FUNCTION trg_grievance_comment_guard();

-- ---------------------------------------------------------------------------------------
-- Admin closes a grievance as Resolved (approved) or Rejected, with a note. Runs in the caller's
-- transaction; the triggers above stamp the time and log the change.
CREATE PROCEDURE resolve_grievance(p_grievance_id int, p_admin_user_id int, p_outcome grievance_status, p_note text)
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM app_user WHERE user_id = p_admin_user_id AND role = 'admin' AND is_active) THEN
    RAISE EXCEPTION 'only an admin can close a grievance' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF p_outcome NOT IN ('Resolved', 'Rejected') THEN
    RAISE EXCEPTION 'a grievance is closed as Resolved or Rejected, not %', p_outcome USING ERRCODE = 'check_violation';
  END IF;
  PERFORM set_config('erp.user_id', p_admin_user_id::text, true);
  UPDATE grievance SET status = p_outcome, resolution_note = btrim(p_note), resolved_by = p_admin_user_id
   WHERE grievance_id = p_grievance_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'unknown grievance %', p_grievance_id USING ERRCODE = 'no_data_found';
  END IF;
END $$;

-- Admin assigns (or, with NULL, unassigns) a faculty member; the trigger moves Open -> In progress.
CREATE PROCEDURE assign_grievance(p_grievance_id int, p_faculty_id int, p_admin_user_id int)
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM app_user WHERE user_id = p_admin_user_id AND role = 'admin' AND is_active) THEN
    RAISE EXCEPTION 'only an admin can assign a grievance' USING ERRCODE = 'insufficient_privilege';
  END IF;
  PERFORM set_config('erp.user_id', p_admin_user_id::text, true);
  UPDATE grievance SET assigned_to = p_faculty_id WHERE grievance_id = p_grievance_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'unknown grievance %', p_grievance_id USING ERRCODE = 'no_data_found';
  END IF;
END $$;

-- ---------------------------------------------------------------------------------------
-- One row per grievance with the names the pages need.
CREATE VIEW v_grievance_overview AS
SELECT g.grievance_id, g.category, g.subject, g.description, g.status,
       g.raised_by, g.raised_by_role, r.login_id AS raised_by_login, r.display_name AS raised_by_name,
       r.dept_id AS raised_by_dept,
       g.assigned_to, g.assigned_at, f.faculty_code AS assigned_code,
       f.first_name || ' ' || f.last_name AS assigned_name, fu.user_id AS assigned_user_id,
       g.resolution_note, g.resolved_by, g.resolved_at, g.created_at, g.updated_at,
       (SELECT count(*) FROM grievance_comment c WHERE c.grievance_id = g.grievance_id)::int AS comment_count,
       round(extract(epoch FROM COALESCE(g.resolved_at, now()) - g.created_at)::numeric / 86400, 1) AS age_days
FROM grievance g
JOIN v_user_profile r ON r.user_id = g.raised_by
LEFT JOIN faculty f ON f.faculty_id = g.assigned_to
LEFT JOIN app_user fu ON fu.faculty_id = g.assigned_to;

-- Report: workload and average resolution time per category (every category listed, even unused).
CREATE VIEW v_grievance_resolution_stats AS
SELECT c.category,
       count(g.grievance_id)::int                                              AS total,
       count(*) FILTER (WHERE g.status = 'Open')::int                          AS open,
       count(*) FILTER (WHERE g.status = 'In progress')::int                   AS in_progress,
       count(*) FILTER (WHERE g.status = 'Resolved')::int                      AS resolved,
       count(*) FILTER (WHERE g.status = 'Rejected')::int                      AS rejected,
       round((avg(extract(epoch FROM g.resolved_at - g.created_at))
              FILTER (WHERE g.status = 'Resolved') / 86400)::numeric, 1)       AS avg_days_to_resolve,
       round((avg(extract(epoch FROM g.resolved_at - g.created_at))
              FILTER (WHERE g.resolved_at IS NOT NULL) / 86400)::numeric, 1)   AS avg_days_to_close,
       round((max(extract(epoch FROM now() - g.created_at))
              FILTER (WHERE g.resolved_at IS NULL) / 86400)::numeric, 1)       AS oldest_open_days
FROM unnest(enum_range(NULL::grievance_category)) AS c (category)
LEFT JOIN grievance g ON g.category = c.category
GROUP BY c.category
ORDER BY c.category;
