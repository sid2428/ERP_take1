-- 006 · Attendance (Group 3), translated to PostgreSQL and stored compactly.
--
-- Storage decision (500 MB free-tier limit): instead of one row per student per session
-- (~3.5M rows), each session row carries the array of ABSENT student ids. The present list
-- is the assignment roster minus that array, so nothing is lost; v_attendance_record turns
-- it back into the normalized (session, student, status) form whenever it is needed.
SET search_path = erp, public;

CREATE TYPE session_status AS ENUM ('Conducted', 'Cancelled');
CREATE TYPE request_status AS ENUM ('Pending', 'Approved', 'Rejected');

CREATE TABLE attendance_session (                -- one row per lecture/lab held (or cancelled) on a date
  session_id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id      int          NOT NULL REFERENCES teaching_assignment,
  timetable_entry_id int          REFERENCES timetable_entry ON DELETE SET NULL,
  session_date       date         NOT NULL,
  session_number     smallint     NOT NULL CHECK (session_number > 0),
  start_period       smallint     REFERENCES time_slot (period_no),
  duration_hrs       numeric(3,1) NOT NULL CHECK (duration_hrs > 0),
  session_status     session_status NOT NULL DEFAULT 'Conducted',
  absent_student_ids int[]        NOT NULL DEFAULT '{}',
  marked_by          int          NOT NULL REFERENCES faculty,
  marked_at          timestamptz,
  UNIQUE (assignment_id, session_date),
  UNIQUE (assignment_id, session_number),
  CHECK (session_status = 'Conducted' OR cardinality(absent_student_ids) = 0),
  CHECK (session_status = 'Cancelled' OR marked_at IS NOT NULL),
  CHECK (array_position(absent_student_ids, NULL) IS NULL)
);
CREATE INDEX ON attendance_session (session_date);

-- Normalise the array (sorted, no duplicates) and check every absentee is on the roster and
-- the date falls inside the term.
CREATE FUNCTION trg_attendance_session_validate() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  bad int;
  term academic_session%ROWTYPE;
BEGIN
  NEW.absent_student_ids := ARRAY(SELECT DISTINCT x FROM unnest(NEW.absent_student_ids) AS x ORDER BY x);

  SELECT x INTO bad FROM unnest(NEW.absent_student_ids) AS x
  EXCEPT SELECT student_id FROM v_assignment_roster WHERE assignment_id = NEW.assignment_id
  LIMIT 1;
  IF bad IS NOT NULL THEN
    RAISE EXCEPTION 'student % is not on the roster of assignment %', bad, NEW.assignment_id
      USING ERRCODE = 'check_violation';
  END IF;

  SELECT s.* INTO term FROM academic_session s
  JOIN teaching_assignment ta ON ta.academic_session_id = s.session_id
  WHERE ta.assignment_id = NEW.assignment_id;
  IF NEW.session_date NOT BETWEEN term.start_date AND term.end_date THEN
    RAISE EXCEPTION 'session date % is outside term % (% to %)', NEW.session_date, term.session_id,
      term.start_date, term.end_date USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER validate BEFORE INSERT OR UPDATE OF absent_student_ids, assignment_id, session_date
  ON attendance_session FOR EACH ROW EXECUTE FUNCTION trg_attendance_session_validate();

CREATE TABLE attendance_summary (                -- per student per course totals (student dashboard)
  student_id          int         NOT NULL REFERENCES student,
  course_id           int         NOT NULL REFERENCES course,
  academic_session_id varchar(10) NOT NULL REFERENCES academic_session,
  assignment_id       int         NOT NULL REFERENCES teaching_assignment,
  total_sessions      smallint    NOT NULL DEFAULT 0,
  attended            smallint    NOT NULL DEFAULT 0,
  absent              smallint GENERATED ALWAYS AS (total_sessions - attended) STORED,
  attendance_pct      numeric(5,2) GENERATED ALWAYS AS (
                        CASE WHEN total_sessions = 0 THEN NULL
                             ELSE round(100.0 * attended / total_sessions, 2) END) STORED,
  last_updated        timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (student_id, course_id, academic_session_id),
  CHECK (attended BETWEEN 0 AND total_sessions)
);
CREATE INDEX ON attendance_summary (assignment_id);

-- Recompute totals for one assignment (or all, when called with NULL). G3 left this re-sync
-- commented out; here it runs automatically from the trigger below.
CREATE FUNCTION refresh_attendance_summary(p_assignment_id int DEFAULT NULL) RETURNS int
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  n int;
BEGIN
  INSERT INTO attendance_summary AS a
         (student_id, course_id, academic_session_id, assignment_id, total_sessions, attended, last_updated)
  SELECT r.student_id, ta.course_id, ta.academic_session_id, ta.assignment_id,
         count(s.session_id) FILTER (WHERE s.session_status = 'Conducted'),
         count(s.session_id) FILTER (WHERE s.session_status = 'Conducted'
                                       AND NOT (r.student_id = ANY (s.absent_student_ids))),
         now()
  FROM teaching_assignment ta
  JOIN v_assignment_roster r ON r.assignment_id = ta.assignment_id
  LEFT JOIN attendance_session s ON s.assignment_id = ta.assignment_id
  WHERE p_assignment_id IS NULL OR ta.assignment_id = p_assignment_id
  GROUP BY r.student_id, ta.course_id, ta.academic_session_id, ta.assignment_id
  ON CONFLICT (student_id, course_id, academic_session_id) DO UPDATE
     SET assignment_id = EXCLUDED.assignment_id, total_sessions = EXCLUDED.total_sessions,
         attended = EXCLUDED.attended, last_updated = EXCLUDED.last_updated
   WHERE (a.total_sessions, a.attended, a.assignment_id)
         IS DISTINCT FROM (EXCLUDED.total_sessions, EXCLUDED.attended, EXCLUDED.assignment_id);
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END $$;

CREATE FUNCTION trg_attendance_session_summary() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    PERFORM refresh_attendance_summary(OLD.assignment_id);
  END IF;
  IF TG_OP = 'INSERT' OR (TG_OP = 'UPDATE' AND NEW.assignment_id <> OLD.assignment_id) THEN
    PERFORM refresh_attendance_summary(NEW.assignment_id);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER keep_summary AFTER INSERT OR UPDATE OR DELETE ON attendance_session
  FOR EACH ROW EXECUTE FUNCTION trg_attendance_session_summary();

-- Faculty request a change to a submitted session; every change needs Admin approval (P2 adds
-- the approval procedure and the audit trail).
CREATE TABLE attendance_correction (
  correction_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id    int         NOT NULL REFERENCES attendance_session ON DELETE CASCADE,
  student_id    int         NOT NULL REFERENCES student,
  from_status   char(1)     NOT NULL CHECK (from_status IN ('P', 'A')),
  to_status     char(1)     NOT NULL CHECK (to_status   IN ('P', 'A')),
  reason        text        NOT NULL CHECK (length(btrim(reason)) >= 5),
  requested_by  int         NOT NULL REFERENCES faculty,
  requested_at  timestamptz NOT NULL DEFAULT now(),
  status        request_status NOT NULL DEFAULT 'Pending',
  reviewed_by   int,                                   -- app user; FK added with authentication
  reviewed_at   timestamptz,
  review_note   text,
  CHECK (from_status <> to_status),
  CHECK ((status = 'Pending') = (reviewed_at IS NULL))
);
CREATE UNIQUE INDEX attendance_correction_one_pending ON attendance_correction (session_id, student_id)
  WHERE status = 'Pending';

-- ---------- Views ----------
CREATE VIEW v_attendance_record AS              -- normalized (session, student, P/A) form
SELECT s.session_id, s.assignment_id, ta.course_id, r.student_id, s.session_date,
       CASE WHEN r.student_id = ANY (s.absent_student_ids) THEN 'A' ELSE 'P' END::char(1) AS status
FROM attendance_session s
JOIN teaching_assignment ta ON ta.assignment_id = s.assignment_id
JOIN v_assignment_roster r  ON r.assignment_id = s.assignment_id
WHERE s.session_status = 'Conducted';

CREATE VIEW v_student_attendance_by_course AS
SELECT a.student_id, a.academic_session_id, c.course_id, c.course_code, c.course_name, c.course_type,
       a.assignment_id, a.total_sessions, a.attended, a.absent, a.attendance_pct, c.min_attendance_pct,
       CASE WHEN a.attendance_pct IS NULL THEN NULL
            WHEN a.attendance_pct >= c.min_attendance_pct THEN 'Eligible' ELSE 'Shortage' END AS eligibility,
       -- consecutive sessions the student must attend to reach the minimum (0 if already there)
       GREATEST(0, ceil((c.min_attendance_pct * a.total_sessions - 100.0 * a.attended)
                        / NULLIF(100 - c.min_attendance_pct, 0)))::int AS sessions_to_recover,
       a.last_updated
FROM attendance_summary a JOIN course c USING (course_id);

CREATE VIEW v_student_attendance_overall AS
SELECT student_id, academic_session_id,
       sum(total_sessions) AS total_sessions, sum(attended) AS attended,
       round(100.0 * sum(attended) / NULLIF(sum(total_sessions), 0), 2) AS overall_pct
FROM attendance_summary GROUP BY student_id, academic_session_id;

CREATE VIEW v_faculty_session_sheet AS           -- faculty dashboard: sessions with present/absent counts
SELECT ta.faculty_id, s.session_id, s.session_date, s.start_period, ta.session_type, s.session_status,
       ta.course_id, c.course_code, d.division_code, b.batch_code, o.section_name AS offering_section,
       rc.roster_size,
       CASE WHEN s.session_status = 'Conducted' THEN rc.roster_size - cardinality(s.absent_student_ids) END AS present_count,
       CASE WHEN s.session_status = 'Conducted' THEN cardinality(s.absent_student_ids) END AS absent_count
FROM attendance_session s
JOIN teaching_assignment ta ON ta.assignment_id = s.assignment_id
JOIN course c ON c.course_id = ta.course_id
LEFT JOIN division d ON d.division_id = ta.division_id
LEFT JOIN batch b ON b.batch_id = ta.batch_id
LEFT JOIN course_offering o ON o.offering_id = ta.offering_id
JOIN LATERAL (SELECT count(*)::int AS roster_size FROM v_assignment_roster r
              WHERE r.assignment_id = s.assignment_id) rc ON true;
