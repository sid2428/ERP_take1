-- 008 · Records created through the portal get generated keys. The imported tables kept their
-- group-assigned ids as plain integers; turning the columns into identity columns preserves
-- those ids and continues numbering after the highest one.
SET search_path = erp, public;

ALTER TABLE course  ALTER COLUMN course_id  ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE student ALTER COLUMN student_id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE faculty ALTER COLUMN faculty_id ADD GENERATED BY DEFAULT AS IDENTITY;

SELECT setval(pg_get_serial_sequence('erp.course',  'course_id'),  GREATEST((SELECT max(course_id)  FROM course), 1));
SELECT setval(pg_get_serial_sequence('erp.student', 'student_id'), GREATEST((SELECT max(student_id) FROM student), 1));
SELECT setval(pg_get_serial_sequence('erp.faculty', 'faculty_id'), GREATEST((SELECT max(faculty_id) FROM faculty), 1));

-- sequences created after 007's default-privilege grant are covered by it; this keeps it explicit
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA erp TO erp_app;
