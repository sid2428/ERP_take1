-- 084 · Group 3 examination schema adapted to the portal's PostgreSQL model.
-- Attendance, academic, people, section, and teaching tables already exist in migrations 002-007.
-- Keep attendance in those tables; add only the examination-owned objects here.
SET search_path = erp, public;

CREATE TYPE exam_kind AS ENUM ('MidSem', 'EndSem', 'Supplementary');
CREATE TYPE exam_cycle_state AS ENUM ('Completed', 'Registration Closed', 'Upcoming');
CREATE TYPE exam_mode AS ENUM ('MidSem', 'EndSem Theory', 'Practical/Oral');
CREATE TYPE exam_session AS ENUM ('Morning', 'Afternoon');
CREATE TYPE exam_registration_state AS ENUM ('Registered', 'Blocked');
CREATE TYPE hall_ticket_state AS ENUM ('Pending Issue', 'Issued', 'Withheld');
CREATE TYPE exam_mark_state AS ENUM ('Present', 'Absent', 'Pending', 'NA');
CREATE TYPE exam_result_state AS ENUM ('Pass', 'Fail');
CREATE TYPE semester_result_state AS ENUM ('Pass', 'ATKT');

CREATE TABLE grade_scale (
  grade          varchar(2) PRIMARY KEY,
  min_percentage numeric(5,2) NOT NULL CHECK (min_percentage BETWEEN 0 AND 100),
  max_percentage numeric(5,2) NOT NULL CHECK (max_percentage BETWEEN 0 AND 100),
  grade_points   smallint NOT NULL CHECK (grade_points BETWEEN 0 AND 10),
  description    varchar(30) NOT NULL,
  CHECK (max_percentage >= min_percentage)
);

CREATE TABLE course_exam_scheme (
  course_id          int PRIMARY KEY REFERENCES course,
  internal_max       smallint NOT NULL CHECK (internal_max >= 0),
  midsem_max         smallint NOT NULL CHECK (midsem_max >= 0),
  endsem_max         smallint NOT NULL CHECK (endsem_max >= 0),
  total_max          smallint NOT NULL CHECK (total_max > 0),
  passing_percentage smallint NOT NULL DEFAULT 40 CHECK (passing_percentage BETWEEN 0 AND 100),
  CHECK (total_max = internal_max + midsem_max + endsem_max)
);

CREATE TABLE exam_cycle (
  exam_cycle_id      int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_session_id varchar(10) NOT NULL REFERENCES academic_session,
  exam_type          exam_kind NOT NULL,
  start_date         date NOT NULL,
  end_date           date NOT NULL,
  registration_open  date,
  registration_close date,
  status             exam_cycle_state NOT NULL,
  CHECK (end_date >= start_date),
  CHECK (registration_close IS NULL OR registration_open IS NULL OR registration_close >= registration_open)
);
CREATE INDEX ON exam_cycle (academic_session_id, status);

CREATE TABLE exam_schedule (
  schedule_id   int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exam_cycle_id int NOT NULL REFERENCES exam_cycle ON DELETE CASCADE,
  course_id     int NOT NULL REFERENCES course,
  exam_mode     exam_mode NOT NULL,
  exam_date     date NOT NULL,
  session       exam_session NOT NULL,
  start_time    time NOT NULL,
  end_time      time NOT NULL,
  duration_min  smallint NOT NULL CHECK (duration_min > 0),
  max_marks     smallint NOT NULL CHECK (max_marks > 0),
  UNIQUE (exam_cycle_id, course_id, exam_mode),
  CHECK (end_time > start_time)
);
CREATE INDEX ON exam_schedule (exam_date, session);

CREATE TABLE exam_registration (
  registration_id       int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id            int NOT NULL REFERENCES student,
  course_id             int NOT NULL REFERENCES course,
  exam_cycle_id         int NOT NULL REFERENCES exam_cycle,
  attendance_percentage numeric(5,2) NOT NULL DEFAULT 0
                          CHECK (attendance_percentage BETWEEN 0 AND 100),
  registration_status   exam_registration_state NOT NULL,
  blocked_reason        varchar(100),
  registered_on         timestamptz,
  UNIQUE (student_id, course_id, exam_cycle_id)
);
CREATE INDEX ON exam_registration (exam_cycle_id, registration_status);
CREATE INDEX ON exam_registration (student_id, exam_cycle_id);

CREATE TABLE hall_ticket (
  hall_ticket_id    int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id       int NOT NULL REFERENCES student,
  exam_cycle_id    int NOT NULL REFERENCES exam_cycle,
  hall_ticket_no   varchar(20) UNIQUE,
  courses_registered smallint NOT NULL CHECK (courses_registered >= 0),
  courses_blocked  smallint NOT NULL CHECK (courses_blocked >= 0),
  status           hall_ticket_state NOT NULL,
  issued_on        date,
  UNIQUE (student_id, exam_cycle_id)
);

CREATE TABLE exam_marks (
  marks_id       int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id     int NOT NULL REFERENCES student,
  course_id      int NOT NULL REFERENCES course,
  attempt_no     smallint NOT NULL DEFAULT 1 CHECK (attempt_no > 0),
  exam_cycle_id  int NOT NULL REFERENCES exam_cycle,
  internal_marks numeric(5,1) CHECK (internal_marks >= 0),
  midsem_marks   numeric(5,1) CHECK (midsem_marks >= 0),
  endsem_marks   numeric(5,1) CHECK (endsem_marks >= 0),
  endsem_status  exam_mark_state NOT NULL,
  entered_by     int REFERENCES faculty,
  last_updated   timestamptz,
  UNIQUE (student_id, course_id, attempt_no)
);
CREATE INDEX ON exam_marks (course_id, exam_cycle_id);

CREATE TABLE course_result (
  result_id        int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id       int NOT NULL REFERENCES student,
  course_id        int NOT NULL REFERENCES course,
  academic_session_id varchar(10) NOT NULL REFERENCES academic_session,
  semester         smallint NOT NULL CHECK (semester BETWEEN 1 AND 12),
  attempt_no       smallint NOT NULL CHECK (attempt_no > 0),
  total_marks      smallint NOT NULL CHECK (total_marks >= 0),
  max_marks        smallint NOT NULL CHECK (max_marks > 0),
  percentage       numeric(5,2) NOT NULL CHECK (percentage BETWEEN 0 AND 100),
  grade            varchar(2) NOT NULL REFERENCES grade_scale,
  grade_points     smallint NOT NULL CHECK (grade_points BETWEEN 0 AND 10),
  result_status    exam_result_state NOT NULL,
  is_final_attempt boolean NOT NULL,
  UNIQUE (student_id, course_id, attempt_no),
  CHECK (total_marks <= max_marks)
);
CREATE INDEX ON course_result (student_id, academic_session_id, is_final_attempt);

CREATE TABLE semester_result (
  semester_result_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id         int NOT NULL REFERENCES student,
  academic_session_id varchar(10) NOT NULL REFERENCES academic_session,
  semester           smallint NOT NULL CHECK (semester BETWEEN 1 AND 12),
  credits_registered smallint NOT NULL CHECK (credits_registered >= 0),
  credits_earned     smallint NOT NULL CHECK (credits_earned BETWEEN 0 AND credits_registered),
  sgpa               numeric(4,2) NOT NULL CHECK (sgpa BETWEEN 0 AND 10),
  backlogs           smallint NOT NULL CHECK (backlogs >= 0),
  result_status      semester_result_state NOT NULL,
  UNIQUE (student_id, academic_session_id)
);

CREATE TABLE student_cgpa (
  student_id         int PRIMARY KEY REFERENCES student,
  semesters_completed smallint NOT NULL CHECK (semesters_completed >= 0),
  credits_attempted  smallint NOT NULL CHECK (credits_attempted >= 0),
  credits_earned     smallint NOT NULL CHECK (credits_earned BETWEEN 0 AND credits_attempted),
  cgpa               numeric(4,2) NOT NULL CHECK (cgpa BETWEEN 0 AND 10),
  backlog_count      smallint NOT NULL CHECK (backlog_count >= 0)
);

CREATE FUNCTION calculate_cgpa(p_student_id int) RETURNS numeric(4,2)
LANGUAGE sql STABLE SET search_path = erp, public AS $$
  SELECT round((sum(c.credits * r.grade_points) / NULLIF(sum(c.credits), 0))::numeric, 2)::numeric(4,2)
  FROM course_result r
  JOIN course c USING (course_id)
  WHERE r.student_id = p_student_id AND r.is_final_attempt
$$;

CREATE FUNCTION trg_exam_registration_attendance() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  current_pct numeric(5,2);
  minimum_pct smallint;
BEGIN
  SELECT a.attendance_pct, c.min_attendance_pct
    INTO current_pct, minimum_pct
  FROM exam_cycle ec
  JOIN course c ON c.course_id = NEW.course_id
  LEFT JOIN v_student_attendance_by_course a
    ON a.student_id = NEW.student_id
   AND a.course_id = NEW.course_id
   AND a.academic_session_id = ec.academic_session_id
  WHERE ec.exam_cycle_id = NEW.exam_cycle_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'exam cycle or course does not exist'
      USING ERRCODE = 'foreign_key_violation';
  END IF;

  NEW.attendance_percentage := COALESCE(current_pct, 0);
  IF NEW.registration_status = 'Registered'
     AND (current_pct IS NULL OR current_pct < minimum_pct) THEN
    RAISE EXCEPTION 'exam registration blocked: attendance is below the course minimum'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER exam_registration_attendance
  BEFORE INSERT OR UPDATE OF student_id, course_id, exam_cycle_id, registration_status
  ON exam_registration FOR EACH ROW EXECUTE FUNCTION trg_exam_registration_attendance();

CREATE VIEW v_student_result_sheet AS
SELECT s.student_number, r.academic_session_id, r.semester, c.course_id, c.course_code, c.course_name,
       c.credits, r.total_marks, r.max_marks, r.percentage, r.grade, r.grade_points,
       r.result_status, r.attempt_no
FROM course_result r
JOIN student s USING (student_id)
JOIN course c USING (course_id)
WHERE r.is_final_attempt;

CREATE VIEW v_student_exam_timetable AS
SELECT s.student_number, c.course_code, c.course_name, sch.exam_mode, sch.exam_date,
       sch.session, sch.start_time, sch.end_time, cy.exam_cycle_id, cy.academic_session_id
FROM exam_registration reg
JOIN student s USING (student_id)
JOIN exam_cycle cy USING (exam_cycle_id)
JOIN exam_schedule sch ON sch.exam_cycle_id = reg.exam_cycle_id AND sch.course_id = reg.course_id
JOIN course c ON c.course_id = reg.course_id
WHERE reg.registration_status = 'Registered' AND sch.exam_mode <> 'MidSem';

CREATE VIEW v_faculty_marks_entry AS
SELECT ta.faculty_id, ta.assignment_id, m.marks_id, s.student_number, m.course_id,
       m.internal_marks, m.midsem_marks, m.endsem_marks, m.endsem_status
FROM exam_marks m
JOIN student s USING (student_id)
JOIN exam_cycle cy USING (exam_cycle_id)
JOIN teaching_assignment ta
  ON ta.course_id = m.course_id AND ta.academic_session_id = cy.academic_session_id
JOIN v_assignment_roster roster
  ON roster.assignment_id = ta.assignment_id AND roster.student_id = m.student_id
WHERE cy.status <> 'Completed';
