-- 099 · HOD Department Meetings
-- HOD can schedule department meetings for faculty, students, or both in their own department.
-- Meeting invites and notifications are automatically delivered to all active department members.
SET search_path = erp, public;

CREATE TABLE IF NOT EXISTS department_meeting (
  meeting_id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dept_id                varchar(10) NOT NULL REFERENCES department(dept_id) ON DELETE RESTRICT,
  created_by_faculty_id  int NOT NULL REFERENCES faculty(faculty_id) ON DELETE RESTRICT,
  title                  varchar(150) NOT NULL CHECK (length(btrim(title)) >= 3),
  agenda                 text NOT NULL CHECK (length(btrim(agenda)) >= 5),
  meeting_date           date NOT NULL,
  start_time             time NOT NULL,
  end_time               time NOT NULL CHECK (end_time > start_time),
  venue                  varchar(150) NOT NULL,
  meeting_link           text,
  target_audience        varchar(20) NOT NULL CHECK (target_audience IN ('faculty', 'student', 'all')),
  status                 varchar(20) NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
  cancel_reason          text,
  created_at             timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_dept_meeting_dept_date ON department_meeting (dept_id, meeting_date DESC);
CREATE INDEX IF NOT EXISTS idx_dept_meeting_creator ON department_meeting (created_by_faculty_id);

CREATE TABLE IF NOT EXISTS department_meeting_participant (
  meeting_id   int NOT NULL REFERENCES department_meeting(meeting_id) ON DELETE CASCADE,
  user_id      int NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
  role         user_role NOT NULL,
  status       varchar(20) NOT NULL DEFAULT 'INVITED' CHECK (status IN ('INVITED', 'ACCEPTED', 'DECLINED')),
  responded_at timestamptz,
  PRIMARY KEY (meeting_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_dept_meeting_part_user ON department_meeting_participant (user_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON department_meeting TO erp_app;
GRANT USAGE, SELECT ON SEQUENCE department_meeting_meeting_id_seq TO erp_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON department_meeting_participant TO erp_app;

CREATE OR REPLACE FUNCTION trg_department_meeting_notify() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  v_hod_name text;
  v_dept_name text;
  v_title text;
  v_text text;
BEGIN
  SELECT (f.first_name || ' ' || f.last_name), d.dept_name INTO v_hod_name, v_dept_name
  FROM department d
  JOIN faculty f ON f.faculty_id = d.hod_faculty_id
  WHERE d.dept_id = NEW.dept_id;

  v_title := 'Meeting: ' || left(NEW.title, 130);
  v_text := format('Department Meeting Scheduled by HOD %s (%s)%sTitle: %s%sDate: %s | Time: %s - %s%sVenue: %s%sAgenda: %s',
                   COALESCE(v_hod_name, 'HOD'), COALESCE(v_dept_name, NEW.dept_id), E'\n',
                   NEW.title, E'\n',
                   NEW.meeting_date, to_char(NEW.start_time, 'HH12:MI AM'), to_char(NEW.end_time, 'HH12:MI AM'), E'\n',
                   NEW.venue, E'\n',
                   left(NEW.agenda, 300));

  -- 1. If audience includes faculty: invite and notify department faculty
  IF NEW.target_audience IN ('faculty', 'all') THEN
    INSERT INTO department_meeting_participant (meeting_id, user_id, role, status)
    SELECT NEW.meeting_id, u.user_id, 'faculty', 'INVITED'
    FROM app_user u
    JOIN faculty f ON f.faculty_id = u.faculty_id
    WHERE f.dept_id = NEW.dept_id AND u.is_active AND u.role = 'faculty'
    ON CONFLICT (meeting_id, user_id) DO NOTHING;

    INSERT INTO notification (user_id, kind, title, text, category, link, created_at, expires_at)
    SELECT u.user_id, 'academic', v_title, v_text, 'Academic', '/faculty/meetings', now(), now() + interval '30 days'
    FROM app_user u
    JOIN faculty f ON f.faculty_id = u.faculty_id
    WHERE f.dept_id = NEW.dept_id AND u.is_active AND u.role = 'faculty'
    ON CONFLICT DO NOTHING;
  END IF;

  -- 2. If audience includes students: invite and notify department students
  IF NEW.target_audience IN ('student', 'all') THEN
    INSERT INTO department_meeting_participant (meeting_id, user_id, role, status)
    SELECT NEW.meeting_id, u.user_id, 'student', 'INVITED'
    FROM app_user u
    JOIN student s ON s.student_id = u.student_id
    JOIN program p ON p.program_id = s.program_id
    WHERE p.dept_id = NEW.dept_id AND u.is_active AND u.role = 'student' AND s.status = 'Active'
    ON CONFLICT (meeting_id, user_id) DO NOTHING;

    INSERT INTO notification (user_id, kind, title, text, category, link, created_at, expires_at)
    SELECT u.user_id, 'academic', v_title, v_text, 'Academic', '/student/meetings', now(), now() + interval '30 days'
    FROM app_user u
    JOIN student s ON s.student_id = u.student_id
    JOIN program p ON p.program_id = s.program_id
    WHERE p.dept_id = NEW.dept_id AND u.is_active AND u.role = 'student' AND s.status = 'Active'
    ON CONFLICT DO NOTHING;
  END IF;

  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_dept_meeting_notify ON department_meeting;
CREATE TRIGGER trg_dept_meeting_notify
  AFTER INSERT ON department_meeting
  FOR EACH ROW EXECUTE FUNCTION trg_department_meeting_notify();
