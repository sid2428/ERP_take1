-- 042 · T3-3 Syllabus coverage: schema, rules, procedure and views.
-- Unit titles are seeded by 043 and coverage of existing attendance sessions by 044.
-- Depends on: 002 (course), 004 (teaching_assignment), 006 (attendance_session).
-- Each conducted attendance session can be tagged with the one unit that was taught in it; progress is
-- the number of tagged sessions per unit against the unit's planned lectures.
SET search_path = erp, public;

CREATE TABLE course_unit (
  unit_id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id        int          NOT NULL REFERENCES course ON DELETE CASCADE,
  unit_no          smallint     NOT NULL CHECK (unit_no BETWEEN 1 AND 5),
  unit_title       varchar(150) NOT NULL CHECK (length(btrim(unit_title)) > 0),
  planned_lectures smallint     NOT NULL CHECK (planned_lectures BETWEEN 1 AND 30),
  UNIQUE (course_id, unit_no)
);

CREATE TABLE syllabus_coverage (
  session_id int         PRIMARY KEY REFERENCES attendance_session ON DELETE CASCADE,   -- one unit per session
  unit_id    int         NOT NULL REFERENCES course_unit ON DELETE CASCADE,
  tagged_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON syllabus_coverage (unit_id);

-- A session can only be tagged if it was conducted and the unit belongs to the course taught in it.
CREATE FUNCTION trg_syllabus_coverage_check() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  s_course int;
  s_status session_status;
  u_course int;
BEGIN
  SELECT ta.course_id, s.session_status INTO s_course, s_status
    FROM attendance_session s JOIN teaching_assignment ta USING (assignment_id)
   WHERE s.session_id = NEW.session_id;
  IF s_status IS DISTINCT FROM 'Conducted' THEN
    RAISE EXCEPTION 'only a conducted session can be tagged with a unit (session %)', NEW.session_id
      USING ERRCODE = 'check_violation';
  END IF;
  SELECT course_id INTO u_course FROM course_unit WHERE unit_id = NEW.unit_id;
  IF u_course IS DISTINCT FROM s_course THEN
    RAISE EXCEPTION 'unit % does not belong to the course taught in session %', NEW.unit_id, NEW.session_id
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER unit_matches_session BEFORE INSERT OR UPDATE OF session_id, unit_id ON syllabus_coverage
  FOR EACH ROW EXECUTE FUNCTION trg_syllabus_coverage_check();

-- Called by the attendance-marking page (T4) or the faculty coverage page: only the faculty member
-- who is assigned to the class may tag or re-tag its sessions.
CREATE PROCEDURE tag_session_unit(p_session_id int, p_unit_id int, p_faculty_id int)
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM attendance_session s JOIN teaching_assignment ta USING (assignment_id)
                  WHERE s.session_id = p_session_id AND ta.faculty_id = p_faculty_id) THEN
    RAISE EXCEPTION 'faculty % did not take session %', p_faculty_id, p_session_id
      USING ERRCODE = 'check_violation';
  END IF;
  INSERT INTO syllabus_coverage (session_id, unit_id) VALUES (p_session_id, p_unit_id)
  ON CONFLICT (session_id) DO UPDATE SET unit_id = EXCLUDED.unit_id, tagged_at = now();
END $$;

-- ---------- Views ----------
-- One row per class (teaching assignment) and unit: planned vs delivered lectures.
CREATE VIEW v_course_syllabus_progress AS
WITH delivered AS (
  SELECT s.assignment_id, sc.unit_id, count(*)::int AS n
  FROM syllabus_coverage sc JOIN attendance_session s ON s.session_id = sc.session_id
  GROUP BY s.assignment_id, sc.unit_id
)
SELECT ta.assignment_id, ta.academic_session_id, ta.course_id, ta.faculty_id,
       ta.division_id, ta.batch_id, ta.offering_id,
       u.unit_id, u.unit_no, u.unit_title, u.planned_lectures,
       COALESCE(d.n, 0) AS delivered,
       round(100.0 * LEAST(COALESCE(d.n, 0), u.planned_lectures) / u.planned_lectures, 0) AS pct
FROM teaching_assignment ta
JOIN course_unit u ON u.course_id = ta.course_id
LEFT JOIN delivered d ON d.assignment_id = ta.assignment_id AND d.unit_id = u.unit_id;

-- One row per class: the overall syllabus bar (a unit never counts above its plan).
CREATE VIEW v_assignment_syllabus_summary AS
SELECT assignment_id, academic_session_id, course_id, faculty_id, division_id, batch_id, offering_id,
       sum(planned_lectures)::int                          AS planned_total,
       sum(LEAST(delivered, planned_lectures))::int        AS delivered_total,
       count(*) FILTER (WHERE delivered >= planned_lectures)::int AS units_done,
       count(*)::int                                       AS units_total,
       round(100.0 * sum(LEAST(delivered, planned_lectures)) / NULLIF(sum(planned_lectures), 0), 0) AS pct
FROM v_course_syllabus_progress
GROUP BY assignment_id, academic_session_id, course_id, faculty_id, division_id, batch_id, offering_id;

-- What a student sees per course: the coverage of the class they sit in.
CREATE VIEW v_student_syllabus_coverage AS
SELECT r.student_id, a.academic_session_id, a.course_id, a.assignment_id,
       a.planned_total, a.delivered_total, a.units_done, a.units_total, a.pct
FROM v_assignment_roster r
JOIN v_assignment_syllabus_summary a ON a.assignment_id = r.assignment_id;
