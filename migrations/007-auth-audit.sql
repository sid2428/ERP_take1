-- 007 · Accounts, login sessions, audit log, and the application's least-privilege role.
--
-- The web app connects as `erp_app`, which can read/write ERP data but cannot change the schema,
-- truncate tables or touch anything outside `erp`. Migrations and bulk loads run as the owner.
SET search_path = erp, public;

CREATE TYPE user_role AS ENUM ('student', 'faculty', 'admin');

CREATE TABLE app_user (
  user_id              int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login_id             varchar(20) NOT NULL UNIQUE,     -- student number / faculty code / admin username
  role                 user_role   NOT NULL,
  student_id           int UNIQUE REFERENCES student,
  faculty_id           int UNIQUE REFERENCES faculty,
  password_hash        text        NOT NULL,            -- scrypt$N$r$p$salt$hash (see src/auth/password.ts)
  must_change_password boolean     NOT NULL DEFAULT true,
  is_active            boolean     NOT NULL DEFAULT true,
  failed_logins        smallint    NOT NULL DEFAULT 0 CHECK (failed_logins >= 0),
  locked_until         timestamptz,
  last_login_at        timestamptz,
  password_changed_at  timestamptz,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  -- a student account points at exactly one student, a faculty account at one faculty member
  CHECK ((role = 'student') = (student_id IS NOT NULL)),
  CHECK ((role = 'faculty') = (faculty_id IS NOT NULL))
);
CREATE TRIGGER touch BEFORE UPDATE ON app_user FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

-- Display name and home department for any account, without storing them twice.
CREATE VIEW v_user_profile AS
SELECT u.user_id, u.login_id, u.role, u.student_id, u.faculty_id, u.is_active, u.must_change_password,
       CASE u.role
         WHEN 'student' THEN s.first_name || ' ' || s.last_name
         WHEN 'faculty' THEN f.first_name || ' ' || f.last_name
         ELSE 'Administrator'
       END AS display_name,
       COALESCE(p.dept_id, f.dept_id) AS dept_id
FROM app_user u
LEFT JOIN student s ON s.student_id = u.student_id
LEFT JOIN program p ON p.program_id = s.program_id
LEFT JOIN faculty f ON f.faculty_id = u.faculty_id;

-- express-session store (connect-pg-simple layout).
CREATE TABLE user_session (
  sid    varchar      NOT NULL PRIMARY KEY,
  sess   json         NOT NULL,
  expire timestamp(6) NOT NULL
);
CREATE INDEX ON user_session (expire);

-- Who did what: approvals, marks, payments, account changes, logins.
CREATE TABLE audit_log (
  audit_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  user_id     int REFERENCES app_user ON DELETE SET NULL,
  action      varchar(40) NOT NULL,                     -- e.g. LOGIN, COURSE_UPDATE, PASSWORD_RESET
  entity      varchar(40) NOT NULL,                     -- e.g. course, student, app_user
  entity_id   varchar(40),
  details     jsonb,
  ip_address  inet
);
CREATE INDEX ON audit_log (occurred_at DESC);
CREATE INDEX ON audit_log (entity, entity_id);

ALTER TABLE attendance_correction
  ADD CONSTRAINT attendance_correction_reviewer_fk FOREIGN KEY (reviewed_by) REFERENCES app_user;

-- ---------------------------------------------------------------------------------------
-- Least-privilege application role. Its password is set separately
-- (npm run db:app-password) so no secret ever lives in a migration.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'erp_app') THEN
    CREATE ROLE erp_app LOGIN;
  END IF;
END $$;
ALTER ROLE erp_app SET search_path = erp, public;   -- app SQL can use unqualified names
ALTER ROLE erp_app SET timezone = 'Asia/Kolkata';   -- college time
ALTER ROLE erp_app SET statement_timeout = '15s';

GRANT USAGE ON SCHEMA erp TO erp_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA erp TO erp_app;
REVOKE INSERT, UPDATE, DELETE ON erp.schema_migrations FROM erp_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA erp TO erp_app;
GRANT EXECUTE ON ALL ROUTINES IN SCHEMA erp TO erp_app;
-- objects created by later migrations get the same rights automatically
ALTER DEFAULT PRIVILEGES IN SCHEMA erp GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO erp_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA erp GRANT USAGE, SELECT ON SEQUENCES TO erp_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA erp GRANT EXECUTE ON ROUTINES TO erp_app;
