-- 041 · T3-2 Elective selection (open electives O1, honors H1).
-- Flow: admin creates a window and picks its offerings -> students rank them while it is Open ->
-- admin closes it -> CALL allocate_electives(window_id) fills seats by merit and preference.
-- Depends on: 002 (academic_session), 003 (student), 004 (course_offering, student_enrollment and its
-- seat trigger), 006 (v_student_attendance_overall). If T5's v_student_academic_standing exists the
-- procedure ranks by CGPA automatically; otherwise it uses overall attendance %.
SET search_path = erp, public;

CREATE TYPE elective_window_status AS ENUM ('Scheduled', 'Open', 'Closed', 'Allocated');

-- Lets the composite FK below prove an offering belongs to the window's session.
ALTER TABLE course_offering
  ADD CONSTRAINT course_offering_id_session_key UNIQUE (offering_id, academic_session_id);

CREATE TABLE elective_window (
  window_id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_session_id varchar(10) NOT NULL REFERENCES academic_session,   -- term the electives run in
  semester_no         smallint    NOT NULL CHECK (semester_no BETWEEN 1 AND 12),
  elective_group      varchar(4)  NOT NULL CHECK (elective_group IN ('O1', 'H1')),
  opens_at            timestamptz NOT NULL,
  closes_at           timestamptz NOT NULL,
  status              elective_window_status NOT NULL DEFAULT 'Scheduled',
  max_choices         smallint    NOT NULL DEFAULT 3 CHECK (max_choices BETWEEN 1 AND 5),
  allocated_at        timestamptz,
  allocated_by        int REFERENCES app_user ON DELETE SET NULL,
  created_at          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (academic_session_id, semester_no, elective_group),
  CHECK (closes_at > opens_at),
  CHECK ((status = 'Allocated') = (allocated_at IS NOT NULL))
);

-- Which offerings a student may rank in this window.
CREATE TABLE elective_window_offering (
  window_id           int         NOT NULL REFERENCES elective_window ON DELETE CASCADE,
  offering_id         int         NOT NULL,
  academic_session_id varchar(10) NOT NULL,
  PRIMARY KEY (window_id, offering_id),
  FOREIGN KEY (offering_id, academic_session_id)
    REFERENCES course_offering (offering_id, academic_session_id) ON DELETE CASCADE
);
-- the offering's term must match the window's term
CREATE FUNCTION trg_window_offering_same_session() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  IF NEW.academic_session_id <> (SELECT academic_session_id FROM elective_window WHERE window_id = NEW.window_id) THEN
    RAISE EXCEPTION 'offering % is not in the session of window %', NEW.offering_id, NEW.window_id
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER same_session BEFORE INSERT OR UPDATE ON elective_window_offering
  FOR EACH ROW EXECUTE FUNCTION trg_window_offering_same_session();

CREATE TABLE elective_preference (
  window_id       int         NOT NULL,
  student_id      int         NOT NULL REFERENCES student,
  offering_id     int         NOT NULL,
  preference_rank smallint    NOT NULL CHECK (preference_rank BETWEEN 1 AND 5),
  submitted_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (window_id, student_id, offering_id),
  UNIQUE (window_id, student_id, preference_rank),          -- one offering per rank
  FOREIGN KEY (window_id, offering_id) REFERENCES elective_window_offering ON DELETE CASCADE
);
CREATE INDEX ON elective_preference (window_id, offering_id);
CREATE INDEX ON elective_preference (student_id);

-- Window rule + eligibility, enforced in the database (not only the UI).
CREATE FUNCTION trg_elective_preference_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  w          elective_window%ROWTYPE;
  v_win      int := CASE WHEN TG_OP = 'DELETE' THEN OLD.window_id ELSE NEW.window_id END;
  stu        student%ROWTYPE;
  stu_dept   varchar(10);
  course_dept varchar(10);
BEGIN
  SELECT * INTO w FROM elective_window WHERE window_id = v_win;
  IF NOT FOUND THEN RETURN COALESCE(NEW, OLD); END IF;     -- window itself is being deleted

  IF w.status <> 'Open' OR now() < w.opens_at OR now() > w.closes_at THEN
    RAISE EXCEPTION 'elective window % is not open for choices', v_win USING ERRCODE = 'check_violation';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;

  IF NEW.preference_rank > w.max_choices THEN
    RAISE EXCEPTION 'rank % exceeds the % choices allowed', NEW.preference_rank, w.max_choices
      USING ERRCODE = 'check_violation';
  END IF;

  SELECT * INTO stu FROM student WHERE student_id = NEW.student_id;
  IF stu.status <> 'Active' THEN
    RAISE EXCEPTION 'only active students can choose electives' USING ERRCODE = 'check_violation';
  END IF;

  -- open electives must come from another department
  IF w.elective_group = 'O1' THEN
    SELECT dept_id INTO stu_dept FROM program WHERE program_id = stu.program_id;
    SELECT c.dept_id INTO course_dept FROM course_offering o JOIN course c USING (course_id)
     WHERE o.offering_id = NEW.offering_id;
    IF stu_dept = course_dept THEN
      RAISE EXCEPTION 'an open elective must be from another department' USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER window_guard BEFORE INSERT OR UPDATE OR DELETE ON elective_preference
  FOR EACH ROW EXECUTE FUNCTION trg_elective_preference_guard();

-- Allocation outcome, one row per applicant (offering_id NULL = no seat could be given).
CREATE TABLE elective_allocation (
  window_id       int          NOT NULL REFERENCES elective_window ON DELETE CASCADE,
  student_id      int          NOT NULL REFERENCES student,
  offering_id     int          REFERENCES course_offering ON DELETE SET NULL,
  preference_rank smallint     CHECK (preference_rank BETWEEN 1 AND 5),
  merit_position  int          NOT NULL CHECK (merit_position > 0),
  merit_score     numeric(6,2),
  merit_basis     varchar(12)  NOT NULL CHECK (merit_basis IN ('CGPA', 'ATTENDANCE')),
  allocated_at    timestamptz  NOT NULL DEFAULT now(),
  PRIMARY KEY (window_id, student_id),
  CHECK ((offering_id IS NULL) = (preference_rank IS NULL))
);
CREATE INDEX ON elective_allocation (offering_id);

-- ---------------------------------------------------------------------------------------
-- Seat allocation. Students are served in merit order; each gets the highest-ranked choice that
-- still has a free seat. Seats are written through student_enrollment, so the existing seat trigger
-- keeps enrolled_count and OPEN/FULL correct. Everything runs in the caller's transaction.
CREATE PROCEDURE allocate_electives(p_window_id int, p_admin_user_id int DEFAULT NULL)
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  w      elective_window%ROWTYPE;
  r      record;
  pr     record;
  o      course_offering%ROWTYPE;
  v_sql  text;
  v_basis varchar(12);
  v_sess varchar(10) := current_session_id();    -- attendance is read from the running term
  v_pos  int := 0;
  v_got  boolean;
  n      int;
BEGIN
  SELECT * INTO w FROM elective_window WHERE window_id = p_window_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'unknown elective window %', p_window_id USING ERRCODE = 'no_data_found';
  END IF;
  IF w.status = 'Allocated' THEN
    RAISE EXCEPTION 'window % has already been allocated', p_window_id USING ERRCODE = 'check_violation';
  ELSIF w.status <> 'Closed' THEN
    RAISE EXCEPTION 'close window % before allocating (status is %)', p_window_id, w.status
      USING ERRCODE = 'check_violation';
  END IF;

  IF to_regclass('erp.v_student_academic_standing') IS NOT NULL THEN
    v_basis := 'CGPA';
    v_sql := 'SELECT s.student_id, st.cgpa::numeric AS merit
              FROM (SELECT DISTINCT student_id FROM elective_preference WHERE window_id = $1) s
              LEFT JOIN v_student_academic_standing st ON st.student_id = s.student_id
              ORDER BY merit DESC NULLS LAST, s.student_id';
  ELSE
    v_basis := 'ATTENDANCE';
    v_sql := 'SELECT s.student_id, a.overall_pct::numeric AS merit
              FROM (SELECT DISTINCT student_id FROM elective_preference WHERE window_id = $1) s
              LEFT JOIN v_student_attendance_overall a
                     ON a.student_id = s.student_id AND a.academic_session_id = $2
              ORDER BY merit DESC NULLS LAST, s.student_id';
  END IF;

  FOR r IN EXECUTE v_sql USING p_window_id, v_sess LOOP
    v_pos := v_pos + 1;
    v_got := false;

    FOR pr IN
      SELECT p.offering_id, p.preference_rank FROM elective_preference p
       WHERE p.window_id = p_window_id AND p.student_id = r.student_id
       ORDER BY p.preference_rank
    LOOP
      SELECT * INTO o FROM course_offering WHERE offering_id = pr.offering_id FOR UPDATE;
      CONTINUE WHEN o.status <> 'OPEN' OR o.enrolled_count >= o.max_seats;

      INSERT INTO student_enrollment AS e (student_id, course_id, academic_session_id, offering_id)
      VALUES (r.student_id, o.course_id, o.academic_session_id, o.offering_id)
      ON CONFLICT (student_id, course_id, academic_session_id)
        DO UPDATE SET offering_id = EXCLUDED.offering_id, status = 'Enrolled', enrolled_at = now()
        WHERE e.status = 'Dropped';
      GET DIAGNOSTICS n = ROW_COUNT;
      CONTINUE WHEN n = 0;                       -- already enrolled in this course: try the next choice

      INSERT INTO elective_allocation (window_id, student_id, offering_id, preference_rank,
                                       merit_position, merit_score, merit_basis)
      VALUES (p_window_id, r.student_id, o.offering_id, pr.preference_rank, v_pos, r.merit, v_basis);
      v_got := true;
      EXIT;
    END LOOP;

    IF NOT v_got THEN
      INSERT INTO elective_allocation (window_id, student_id, merit_position, merit_score, merit_basis)
      VALUES (p_window_id, r.student_id, v_pos, r.merit, v_basis);
    END IF;
  END LOOP;

  UPDATE elective_window
     SET status = 'Allocated', allocated_at = now(), allocated_by = p_admin_user_id
   WHERE window_id = p_window_id;
END $$;

-- ---------- Views ----------
CREATE VIEW v_elective_allocation_summary AS
SELECT w.window_id, w.academic_session_id, w.semester_no, w.elective_group, w.status AS window_status,
       o.offering_id, c.course_code, c.course_name, c.dept_id, o.section_name,
       o.max_seats, o.enrolled_count, o.max_seats - o.enrolled_count AS seats_left, o.status AS offering_status,
       count(DISTINCT p.student_id)                                       AS applicants,
       count(DISTINCT p.student_id) FILTER (WHERE p.preference_rank = 1)  AS first_choice_applicants,
       count(DISTINCT a.student_id)                                       AS allocated
FROM elective_window w
JOIN elective_window_offering wo ON wo.window_id = w.window_id
JOIN course_offering o           ON o.offering_id = wo.offering_id
JOIN course c                    ON c.course_id = o.course_id
LEFT JOIN elective_preference p  ON p.window_id = w.window_id AND p.offering_id = o.offering_id
LEFT JOIN elective_allocation a  ON a.window_id = w.window_id AND a.offering_id = o.offering_id
GROUP BY w.window_id, o.offering_id, c.course_id;

CREATE VIEW v_student_elective_result AS
SELECT a.window_id, w.academic_session_id, w.semester_no, w.elective_group, a.student_id,
       a.merit_position, a.merit_score, a.merit_basis, a.preference_rank AS choice_got,
       o.offering_id, c.course_code, c.course_name, o.section_name,
       CASE WHEN a.offering_id IS NULL THEN 'No seat' ELSE 'Allocated' END AS outcome
FROM elective_allocation a
JOIN elective_window w ON w.window_id = a.window_id
LEFT JOIN course_offering o ON o.offering_id = a.offering_id
LEFT JOIN course c ON c.course_id = o.course_id;
