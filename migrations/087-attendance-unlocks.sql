-- Faculty request a temporary unlock for attendance sessions beyond the edit window.
SET search_path = erp, public;

CREATE TABLE attendance_unlock_request (
  request_id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id          int NOT NULL REFERENCES attendance_session ON DELETE CASCADE,
  requested_by        int NOT NULL REFERENCES app_user,
  reason              text NOT NULL CHECK (length(btrim(reason)) BETWEEN 1 AND 500),
  status              text NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'approved', 'rejected')),
  decided_by          int REFERENCES app_user,
  decided_at          timestamptz,
  unlock_expires_at   timestamptz,
  created_at          timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (status = 'pending' AND decided_by IS NULL AND decided_at IS NULL)
    OR (status <> 'pending' AND decided_by IS NOT NULL AND decided_at IS NOT NULL)
  ),
  CHECK ((status = 'approved') = (unlock_expires_at IS NOT NULL))
);
CREATE UNIQUE INDEX attendance_unlock_one_pending
  ON attendance_unlock_request (session_id) WHERE status = 'pending';
CREATE INDEX attendance_unlock_pending_queue
  ON attendance_unlock_request (created_at) WHERE status = 'pending';

CREATE TABLE attendance_session_audit (
  audit_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id   int NOT NULL REFERENCES attendance_session ON DELETE CASCADE,
  request_id   int NOT NULL REFERENCES attendance_unlock_request ON DELETE RESTRICT,
  actor_id     int NOT NULL REFERENCES app_user,
  action       text NOT NULL CHECK (action IN ('attendance_edit', 'unlock_approved', 'unlock_rejected')),
  occurred_at  timestamptz NOT NULL DEFAULT now(),
  old_value    jsonb NOT NULL,
  new_value    jsonb NOT NULL
);
CREATE INDEX attendance_session_audit_history
  ON attendance_session_audit (session_id, occurred_at DESC);
