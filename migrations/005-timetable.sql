-- 005 · Rooms, periods and the weekly timetable.
-- Clash rules live in the database as exclusion constraints: within a term, no room, faculty
-- member or division/batch can be booked into overlapping periods on the same day. A lecture
-- occupies every batch of its division; a lab occupies one batch.
SET search_path = erp, public;

CREATE TYPE room_type AS ENUM ('Classroom', 'Lab');

CREATE TABLE room (
  room_id   int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_code varchar(15) NOT NULL UNIQUE,                   -- e.g. CSE-CR-004, CSE-LAB-002
  dept_id   varchar(10) NOT NULL REFERENCES department,
  room_type room_type   NOT NULL,
  capacity  smallint    NOT NULL CHECK (capacity > 0),
  building  varchar(20)
);

ALTER TABLE course_offering ADD CONSTRAINT course_offering_room_fk FOREIGN KEY (room_id) REFERENCES room;

CREATE TABLE time_slot (
  period_no  smallint PRIMARY KEY CHECK (period_no BETWEEN 1 AND 12),
  start_time time NOT NULL,
  end_time   time NOT NULL,
  CHECK (end_time > start_time)
);

CREATE TABLE timetable_entry (
  entry_id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id       int         NOT NULL,
  -- the next four columns are copied from the assignment by trigger so the exclusion
  -- constraints can see them; faculty changes on the assignment cascade here automatically
  faculty_id          int         NOT NULL,
  academic_session_id varchar(10) NOT NULL,
  division_id         int,                                   -- NULL for honors offerings
  batch_no            smallint,                              -- NULL = the whole division
  day_of_week         smallint    NOT NULL CHECK (day_of_week BETWEEN 1 AND 6),   -- 1 = Monday
  start_period        smallint    NOT NULL REFERENCES time_slot (period_no),
  periods             smallint    NOT NULL CHECK (periods IN (1, 2)),
  room_id             int         NOT NULL REFERENCES room,
  period_range int4range GENERATED ALWAYS AS (int4range(start_period, start_period + periods)) STORED,
  batch_range  int4range GENERATED ALWAYS AS (
                 CASE WHEN batch_no IS NULL THEN int4range(1, 10) ELSE int4range(batch_no, batch_no + 1) END) STORED,
  FOREIGN KEY (assignment_id, faculty_id) REFERENCES teaching_assignment (assignment_id, faculty_id)
    ON UPDATE CASCADE ON DELETE CASCADE,
  CHECK (start_period + periods <= 7),
  CHECK (periods = 1 OR start_period IN (1, 3, 5)),          -- double periods never straddle a break
  CONSTRAINT no_room_clash EXCLUDE USING gist
    (academic_session_id WITH =, room_id WITH =, day_of_week WITH =, period_range WITH &&),
  CONSTRAINT no_faculty_clash EXCLUDE USING gist
    (academic_session_id WITH =, faculty_id WITH =, day_of_week WITH =, period_range WITH &&),
  CONSTRAINT no_division_clash EXCLUDE USING gist
    (academic_session_id WITH =, division_id WITH =, day_of_week WITH =, period_range WITH &&, batch_range WITH &&)
);
CREATE INDEX ON timetable_entry (assignment_id);

CREATE FUNCTION trg_timetable_fill_from_assignment() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  SELECT ta.faculty_id, ta.academic_session_id, ta.division_id, b.batch_no
    INTO NEW.faculty_id, NEW.academic_session_id, NEW.division_id, NEW.batch_no
  FROM teaching_assignment ta LEFT JOIN batch b ON b.batch_id = ta.batch_id
  WHERE ta.assignment_id = NEW.assignment_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'teaching assignment % does not exist', NEW.assignment_id USING ERRCODE = 'foreign_key_violation';
  END IF;
  IF (SELECT session_type FROM teaching_assignment WHERE assignment_id = NEW.assignment_id) = 'Lab'
     AND NEW.periods <> 2 THEN
    RAISE EXCEPTION 'lab sessions take two consecutive periods' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER fill_from_assignment BEFORE INSERT OR UPDATE OF assignment_id, periods ON timetable_entry
  FOR EACH ROW EXECUTE FUNCTION trg_timetable_fill_from_assignment();

CREATE VIEW v_timetable AS
SELECT te.entry_id, te.academic_session_id, te.day_of_week, te.start_period, te.periods,
       ts.start_time, ts_end.end_time, te.assignment_id, ta.session_type,
       c.course_id, c.course_code, c.course_name, c.course_type,
       f.faculty_id, f.faculty_code, f.first_name || ' ' || f.last_name AS faculty_name,
       te.division_id, d.division_code, ta.batch_id, b.batch_code, ta.offering_id, o.section_name AS offering_section,
       r.room_id, r.room_code, r.room_type
FROM timetable_entry te
JOIN teaching_assignment ta USING (assignment_id)
JOIN course c ON c.course_id = ta.course_id
JOIN faculty f ON f.faculty_id = te.faculty_id
JOIN room r ON r.room_id = te.room_id
JOIN time_slot ts ON ts.period_no = te.start_period
JOIN time_slot ts_end ON ts_end.period_no = te.start_period + te.periods - 1
LEFT JOIN division d ON d.division_id = te.division_id
LEFT JOIN batch b ON b.batch_id = ta.batch_id
LEFT JOIN course_offering o ON o.offering_id = ta.offering_id;
