-- 091 · Fees, online payments (Razorpay) and the D-Wallet.
-- Depends on: 001 (touch_updated_at), 003 (student), 007 (the erp_app role).
-- Originally 042; renumbered because main already has 042-syllabus-coverage and 084–090.
--
-- Design:
--   * Money is stored as integer PAISE (1 rupee = 100 paise): no rounding errors, and it is
--     the unit Razorpay expects.
--   * fee_record is what a student owes. Totals, outstanding balance and status are GENERATED
--     columns, so they cannot disagree with the individual fees (same idea as 006's attendance %).
--   * fee_payment has one row per payment attempt. wallet_txn is an append-only ledger.
--   * apply_fee_payment() applies a confirmed payment in one transaction and is idempotent, so the
--     browser callback and Razorpay's webhook can both call it safely.
SET search_path = erp, public;

CREATE TYPE fee_status      AS ENUM ('UNPAID', 'PARTIAL', 'PAID');
CREATE TYPE payment_purpose AS ENUM ('FEE', 'TOPUP');
CREATE TYPE payment_gateway AS ENUM ('RAZORPAY', 'SIMULATED');
CREATE TYPE payment_status  AS ENUM ('CREATED', 'SUCCESS', 'FAILED', 'CANCELLED');
CREATE TYPE wallet_txn_kind AS ENUM ('OPENING', 'TOPUP', 'EXCESS_CREDIT', 'ADJUSTMENT');

-- ---------------------------------------------------------------------------------------
-- What each student owes for an academic year
CREATE TABLE fee_record (
  fee_record_id      varchar(30) PRIMARY KEY,                       -- e.g. FEE2627-STU202600004
  student_id         int         NOT NULL REFERENCES student,
  academic_year      varchar(7)  NOT NULL CHECK (academic_year ~ '^\d{4}-\d{2}$'),

  tuition_paise      bigint      NOT NULL CHECK (tuition_paise     >= 0),
  development_paise  bigint      NOT NULL CHECK (development_paise >= 0),
  examination_paise  bigint      NOT NULL CHECK (examination_paise >= 0),
  other_paise        bigint      NOT NULL CHECK (other_paise       >= 0),
  late_fee_paise     bigint      NOT NULL DEFAULT 0 CHECK (late_fee_paise >= 0),

  opening_paid_paise bigint      NOT NULL DEFAULT 0 CHECK (opening_paid_paise >= 0), -- paid before this system (imported)
  online_paid_paise  bigint      NOT NULL DEFAULT 0 CHECK (online_paid_paise  >= 0), -- paid through the portal

  total_fee_paise    bigint GENERATED ALWAYS AS
    (tuition_paise + development_paise + examination_paise + other_paise) STORED,
  total_due_paise    bigint GENERATED ALWAYS AS
    (tuition_paise + development_paise + examination_paise + other_paise + late_fee_paise) STORED,
  paid_paise         bigint GENERATED ALWAYS AS (opening_paid_paise + online_paid_paise) STORED,
  outstanding_paise  bigint GENERATED ALWAYS AS
    (tuition_paise + development_paise + examination_paise + other_paise + late_fee_paise
     - opening_paid_paise - online_paid_paise) STORED,
  fee_status         fee_status GENERATED ALWAYS AS (
    CASE WHEN opening_paid_paise + online_paid_paise = 0 THEN 'UNPAID'::fee_status
         WHEN opening_paid_paise + online_paid_paise >=
              tuition_paise + development_paise + examination_paise + other_paise + late_fee_paise
              THEN 'PAID'::fee_status
         ELSE 'PARTIAL'::fee_status END) STORED,

  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  UNIQUE (student_id, academic_year),
  UNIQUE (fee_record_id, student_id),                               -- target for fee_payment's composite FK
  CONSTRAINT fee_record_not_overpaid CHECK (outstanding_paise >= 0)
);
CREATE INDEX ON fee_record (student_id);
CREATE TRIGGER touch BEFORE UPDATE ON fee_record FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

-- ---------------------------------------------------------------------------------------
-- One row per payment attempt (a fee payment or a wallet top-up)
CREATE TABLE fee_payment (
  payment_id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id         int             NOT NULL REFERENCES student,
  fee_record_id      varchar(30),                                   -- NULL for wallet top-ups
  purpose            payment_purpose NOT NULL,
  gateway            payment_gateway NOT NULL DEFAULT 'RAZORPAY',
  gateway_order_id   varchar(40) UNIQUE,                            -- Razorpay order_id, created before checkout
  gateway_payment_id varchar(40) UNIQUE,                            -- Razorpay payment_id, known once paid
  amount_paise       bigint          NOT NULL CHECK (amount_paise > 0),
  status             payment_status  NOT NULL DEFAULT 'CREATED',
  failure_reason     varchar(200),
  receipt_no         varchar(20) UNIQUE,                            -- assigned only when the payment succeeds
  paid_at            timestamptz,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  UNIQUE (payment_id, student_id),                                  -- target for wallet_txn's composite FK
  -- composite FK: a fee payment must belong to the same student as its fee record
  FOREIGN KEY (fee_record_id, student_id) REFERENCES fee_record (fee_record_id, student_id),
  CONSTRAINT fee_payment_purpose_matches_record CHECK ((purpose = 'FEE') = (fee_record_id IS NOT NULL)),
  CONSTRAINT fee_payment_success_is_complete
    CHECK (status <> 'SUCCESS' OR (receipt_no IS NOT NULL AND paid_at IS NOT NULL AND gateway_payment_id IS NOT NULL))
);
CREATE INDEX ON fee_payment (student_id, created_at DESC);
CREATE INDEX ON fee_payment (fee_record_id);
CREATE TRIGGER touch BEFORE UPDATE ON fee_payment FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

-- ---------------------------------------------------------------------------------------
-- D-Wallet: current balance plus an append-only ledger
CREATE TABLE wallet (
  student_id    int         PRIMARY KEY REFERENCES student,
  balance_paise bigint      NOT NULL DEFAULT 0 CHECK (balance_paise >= 0),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER touch BEFORE UPDATE ON wallet FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

CREATE TABLE wallet_txn (
  txn_id              int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id          int             NOT NULL REFERENCES wallet,
  kind                wallet_txn_kind NOT NULL,
  amount_paise        bigint          NOT NULL CHECK (amount_paise <> 0),
  balance_after_paise bigint          NOT NULL CHECK (balance_after_paise >= 0),
  payment_id          int,
  description         varchar(120),
  created_at          timestamptz     NOT NULL DEFAULT now(),
  -- composite FK: a ledger row tied to a payment must be the same student's payment
  FOREIGN KEY (payment_id, student_id) REFERENCES fee_payment (payment_id, student_id),
  CHECK (kind = 'ADJUSTMENT' OR amount_paise > 0)
);
CREATE INDEX ON wallet_txn (student_id, created_at DESC);
-- a payment credits the wallet at most once (a retried confirmation cannot double-credit)
CREATE UNIQUE INDEX wallet_txn_one_per_payment ON wallet_txn (payment_id) WHERE payment_id IS NOT NULL;
-- each student has at most one imported opening balance
CREATE UNIQUE INDEX wallet_txn_one_opening ON wallet_txn (student_id) WHERE kind = 'OPENING';

-- ---------------------------------------------------------------------------------------
-- Receipt numbers: RCPT-2026-000123
CREATE SEQUENCE fee_receipt_seq;

CREATE FUNCTION next_receipt_no() RETURNS varchar
LANGUAGE sql SET search_path = erp, public AS $$
  SELECT 'RCPT-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('erp.fee_receipt_seq')::text, 6, '0')
$$;

-- Add to a student's wallet and write the ledger row together. Returns the new balance.
CREATE FUNCTION wallet_credit(p_student_id int, p_amount bigint, p_kind wallet_txn_kind,
                              p_payment_id int, p_description varchar) RETURNS bigint
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  v_balance bigint;
BEGIN
  INSERT INTO wallet (student_id, balance_paise) VALUES (p_student_id, p_amount)
  ON CONFLICT (student_id) DO UPDATE SET balance_paise = wallet.balance_paise + EXCLUDED.balance_paise
  RETURNING balance_paise INTO v_balance;

  INSERT INTO wallet_txn (student_id, kind, amount_paise, balance_after_paise, payment_id, description)
  VALUES (p_student_id, p_kind, p_amount, v_balance, p_payment_id, p_description);
  RETURN v_balance;
END $$;

-- Apply a payment the gateway has CONFIRMED (call it after verifying Razorpay's signature, or from
-- the webhook). One transaction: payment -> receipt -> fee record or wallet.
--   * Idempotent: a second call for the same order changes nothing and returns the same row.
--   * If more was paid than is still owed (two open orders both paid), the excess goes to the
--     wallet instead of failing after the money has already been taken.
CREATE FUNCTION apply_fee_payment(p_gateway_order_id varchar, p_gateway_payment_id varchar)
RETURNS fee_payment
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  pay     fee_payment%ROWTYPE;
  rec     fee_record%ROWTYPE;
  applied bigint;
  excess  bigint;
BEGIN
  SELECT * INTO pay FROM fee_payment WHERE gateway_order_id = p_gateway_order_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'unknown payment order %', p_gateway_order_id USING ERRCODE = 'no_data_found';
  END IF;
  IF pay.status = 'SUCCESS' THEN
    RETURN pay;                                         -- already applied
  END IF;

  UPDATE fee_payment
     SET status = 'SUCCESS', gateway_payment_id = p_gateway_payment_id,
         receipt_no = next_receipt_no(), paid_at = now(), failure_reason = NULL
   WHERE payment_id = pay.payment_id
  RETURNING * INTO pay;

  IF pay.purpose = 'FEE' THEN
    SELECT * INTO rec FROM fee_record WHERE fee_record_id = pay.fee_record_id FOR UPDATE;
    applied := LEAST(pay.amount_paise, rec.outstanding_paise);
    excess  := pay.amount_paise - applied;
    UPDATE fee_record SET online_paid_paise = online_paid_paise + applied
     WHERE fee_record_id = rec.fee_record_id;
    IF excess > 0 THEN
      PERFORM wallet_credit(pay.student_id, excess, 'EXCESS_CREDIT', pay.payment_id,
                            'Excess fee payment credited to D-Wallet');
    END IF;
  ELSE
    PERFORM wallet_credit(pay.student_id, pay.amount_paise, 'TOPUP', pay.payment_id, 'D-Wallet top-up');
  END IF;
  RETURN pay;
END $$;

-- ---------------------------------------------------------------------------------------
-- Everything a printed receipt needs, for successful payments only.
-- (The "now" columns come from the fee record, so they show the balance today, not at payment time.)
CREATE VIEW v_fee_receipt AS
SELECT p.payment_id, p.receipt_no, p.paid_at, p.purpose, p.amount_paise,
       p.gateway, p.gateway_order_id, p.gateway_payment_id,
       s.student_id, s.student_number, s.first_name || ' ' || s.last_name AS student_name,
       pr.program_id, pr.program_name, d.dept_id, d.dept_name,
       p.fee_record_id, f.academic_year,
       f.tuition_paise, f.development_paise, f.examination_paise, f.other_paise, f.late_fee_paise,
       f.total_due_paise, f.paid_paise, f.outstanding_paise, f.fee_status
FROM fee_payment p
JOIN student s    ON s.student_id = p.student_id
JOIN program pr   ON pr.program_id = s.program_id
JOIN department d ON d.dept_id = pr.dept_id
LEFT JOIN fee_record f ON f.fee_record_id = p.fee_record_id
WHERE p.status = 'SUCCESS';

-- ---------------------------------------------------------------------------------------
-- Tighter rights than 007's blanket grant, because this is money. Start from nothing, then grant
-- what the app needs: it cannot delete payments, edit the ledger, or rewrite the imported
-- "already paid" amount; paid amounts only move through apply_fee_payment().
REVOKE ALL ON fee_record, fee_payment, wallet, wallet_txn FROM erp_app;
GRANT SELECT, INSERT ON fee_record  TO erp_app;
GRANT UPDATE (online_paid_paise) ON fee_record TO erp_app;
GRANT SELECT, INSERT, UPDATE ON fee_payment TO erp_app;
GRANT SELECT, INSERT, UPDATE ON wallet      TO erp_app;
GRANT SELECT, INSERT         ON wallet_txn  TO erp_app;      -- append-only ledger
GRANT SELECT ON v_fee_receipt TO erp_app;
GRANT USAGE ON SEQUENCE fee_receipt_seq TO erp_app;

