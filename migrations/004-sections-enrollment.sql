-- 004 · Divisions, lab batches, section mapping (Group 3), course offerings and enrollment (Group 2),
-- and teaching assignments (Group 3).
-- Two section models, combined: core courses are taught per division (labs per batch); honors
-- courses use G2-style seat-limited course offerings.
SET search_path = erp, public;

CREATE TYPE offering_status   AS ENUM ('OPEN', 'FULL', 'CLOSED');
CREATE TYPE enrollment_status AS ENUM ('Enrolled', 'Dropped');
CREATE TYPE session_kind      AS ENUM ('Lecture', 'Lab');

CREATE TABLE division (
  division_id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  division_code       varchar(20) NOT NULL UNIQUE,          -- e.g. CSE-Y2-A
  dept_id             varchar(10) NOT NULL REFERENCES department,
  academic_session_id varchar(10) NOT NULL REFERENCES academic_session,
  year_of_study       smallint    NOT NULL CHECK (year_of_study BETWEEN 1 AND 4),
  semester            smallint    NOT NULL,
  UNIQUE (division_id, academic_session_id),
  CHECK (semester IN (2 * year_of_study - 1, 2 * year_of_study))
);
CREATE INDEX ON division (dept_id, year_of_study);

CREATE TABLE batch (                                          -- lab batches inside a division
  batch_id    int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_code  varchar(25) NOT NULL UNIQUE,                    -- e.g. CSE-Y2-A-B1
  division_id int         NOT NULL REFERENCES division,
  batch_no    smallint    NOT NULL CHECK (batch_no BETWEEN 1 AND 9),
  UNIQUE (division_id, batch_no),
  UNIQUE (batch_id, division_id)                              -- target for composite FKs below
);

CREATE TABLE student_section (                                -- student -> division -> batch, per term
  student_id          int         NOT NULL REFERENCES student,
  academic_session_id varchar(10) NOT NULL,
  division_id         int         NOT NULL,
  batch_id            int         NOT NULL,
  roll_no             smallint    NOT NULL CHECK (roll_no > 0),
  PRIMARY KEY (student_id, academic_session_id),
  UNIQUE (division_id, roll_no),
  FOREIGN KEY (division_id, academic_session_id) REFERENCES division (division_id, academic_session_id),
  -- composite FK: the batch must belong to the same division (no trigger needed)
  FOREIGN KEY (batch_id, division_id) REFERENCES batch (batch_id, division_id)
);
CREATE INDEX ON student_section (batch_id);

CREATE TABLE course_offering (                                -- seat-limited sections (honors)
  offering_id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id           int         NOT NULL REFERENCES course,
  academic_session_id varchar(10) NOT NULL REFERENCES academic_session,
  faculty_id          int         REFERENCES faculty,
  section_name        varchar(5)  NOT NULL,
  max_seats           smallint    NOT NULL CHECK (max_seats > 0),
  enrolled_count      smallint    NOT NULL DEFAULT 0,          -- trigger-maintained, never hand-written
  room_id             int,                                     -- FK added in 005
  status              offering_status NOT NULL DEFAULT 'OPEN',
  created_at          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (course_id, academic_session_id, section_name),
  UNIQUE (offering_id, course_id, academic_session_id),
  CHECK (enrolled_count BETWEEN 0 AND max_seats)
);
CREATE TRIGGER require_active_faculty BEFORE INSERT OR UPDATE OF faculty_id ON course_offering
  FOR EACH ROW EXECUTE FUNCTION trg_require_active_faculty();

CREATE TABLE student_enrollment (                             -- course registration per term
  enrollment_id       int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id          int         NOT NULL REFERENCES student,
  course_id           int         NOT NULL REFERENCES course,
  academic_session_id varchar(10) NOT NULL REFERENCES academic_session,
  offering_id         int,
  status              enrollment_status NOT NULL DEFAULT 'Enrolled',
  enrolled_at         timestamptz NOT NULL DEFAULT now(),
  UNIQUE (student_id, course_id, academic_session_id),
  -- the offering must be a section of this very course in this very term
  FOREIGN KEY (offering_id, course_id, academic_session_id)
    REFERENCES course_offering (offering_id, course_id, academic_session_id)
);
CREATE INDEX ON student_enrollment (offering_id) WHERE offering_id IS NOT NULL;
CREATE INDEX ON student_enrollment (course_id, academic_session_id);

-- Seat control (G2): the seat after max_seats is rejected; counts and FULL/OPEN status follow.
CREATE FUNCTION trg_enrollment_seats() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  o course_offering%ROWTYPE;
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') AND OLD.offering_id IS NOT NULL AND OLD.status = 'Enrolled' THEN
    UPDATE course_offering
       SET enrolled_count = enrolled_count - 1,
           status = CASE WHEN status = 'FULL' THEN 'OPEN'::offering_status ELSE status END
     WHERE offering_id = OLD.offering_id;
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') AND NEW.offering_id IS NOT NULL AND NEW.status = 'Enrolled' THEN
    SELECT * INTO o FROM course_offering WHERE offering_id = NEW.offering_id FOR UPDATE;
    IF o.status = 'CLOSED' THEN
      RAISE EXCEPTION 'offering % is closed', NEW.offering_id USING ERRCODE = 'check_violation';
    ELSIF o.enrolled_count >= o.max_seats THEN
      RAISE EXCEPTION 'offering % is already FULL (% seats)', NEW.offering_id, o.max_seats
        USING ERRCODE = 'check_violation';
    END IF;
    UPDATE course_offering
       SET enrolled_count = enrolled_count + 1,
           status = CASE WHEN enrolled_count + 1 >= max_seats THEN 'FULL'::offering_status ELSE status END
     WHERE offering_id = NEW.offering_id;
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER enrollment_seats AFTER INSERT OR UPDATE OF offering_id, status OR DELETE ON student_enrollment
  FOR EACH ROW EXECUTE FUNCTION trg_enrollment_seats();

CREATE TABLE teaching_assignment (                            -- who teaches (and marks attendance for) what
  assignment_id       int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_session_id varchar(10) NOT NULL REFERENCES academic_session,
  course_id           int         NOT NULL REFERENCES course,
  faculty_id          int         NOT NULL REFERENCES faculty,
  division_id         int,
  batch_id            int,
  offering_id         int,
  session_type        session_kind NOT NULL,
  weekly_sessions     smallint    NOT NULL CHECK (weekly_sessions BETWEEN 1 AND 6),
  FOREIGN KEY (division_id, academic_session_id) REFERENCES division (division_id, academic_session_id),
  FOREIGN KEY (batch_id, division_id) REFERENCES batch (batch_id, division_id),
  FOREIGN KEY (offering_id, course_id, academic_session_id)
    REFERENCES course_offering (offering_id, course_id, academic_session_id),
  UNIQUE NULLS NOT DISTINCT (academic_session_id, course_id, division_id, batch_id, offering_id),
  UNIQUE (assignment_id, faculty_id),                         -- target for the timetable's composite FK
  CHECK ((offering_id IS NULL) <> (division_id IS NULL)),     -- taught to a division XOR an offering
  CHECK ((session_type = 'Lab') = (batch_id IS NOT NULL))     -- labs are taught per batch
);
CREATE INDEX ON teaching_assignment (faculty_id, academic_session_id);
CREATE INDEX ON teaching_assignment (division_id);
CREATE TRIGGER require_active_faculty BEFORE INSERT OR UPDATE OF faculty_id ON teaching_assignment
  FOR EACH ROW EXECUTE FUNCTION trg_require_active_faculty();

-- Who sits in each teaching assignment: division/batch members enrolled in the course, or the
-- members of an offering. Attendance, marks and permissions are all resolved through this view.
CREATE VIEW v_assignment_roster AS
SELECT ta.assignment_id, ss.student_id
FROM teaching_assignment ta
JOIN student_section ss
  ON ss.division_id = ta.division_id AND ss.academic_session_id = ta.academic_session_id
 AND (ta.batch_id IS NULL OR ss.batch_id = ta.batch_id)
JOIN student_enrollment e
  ON e.student_id = ss.student_id AND e.course_id = ta.course_id
 AND e.academic_session_id = ta.academic_session_id AND e.status = 'Enrolled' AND e.offering_id IS NULL
WHERE ta.offering_id IS NULL
UNION ALL
SELECT ta.assignment_id, e.student_id
FROM teaching_assignment ta
JOIN student_enrollment e ON e.offering_id = ta.offering_id AND e.status = 'Enrolled'
WHERE ta.offering_id IS NOT NULL;

CREATE VIEW v_division_strength AS
SELECT d.division_id, d.division_code, d.dept_id, d.year_of_study, d.semester, d.academic_session_id,
       count(ss.student_id) AS strength
FROM division d LEFT JOIN student_section ss USING (division_id, academic_session_id)
GROUP BY d.division_id;
