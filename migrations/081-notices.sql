-- 081 · T8-1 Notices.
-- A notice has one or more targets. Each target narrows the audience with optional filters
-- (role, department, year of study, division); a target with no filters is everyone. A notice
-- reaches a user when ANY of its targets matches them. Year and division are taken from the
-- student's division in the current session.
-- Who may post: the admin to anyone; faculty only to divisions they teach this session; NULL
-- poster = a system notice posted by another module (results published, fee reminder, new drive).
-- Contract for other teams: post_notice(...) below.
-- Depends on: 004 (division, student_section, teaching_assignment), 007 (app_user, user_role).
SET search_path = erp, public;

CREATE TYPE notice_category AS ENUM ('General', 'Academic', 'Exam', 'Fees', 'Placement', 'Event');

CREATE TABLE notice (
  notice_id    int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title        varchar(150)    NOT NULL CHECK (length(btrim(title)) >= 5),
  body         text            NOT NULL CHECK (length(btrim(body)) BETWEEN 10 AND 5000),
  category     notice_category NOT NULL DEFAULT 'General',
  is_important boolean         NOT NULL DEFAULT false,       -- pinned to the top of the board
  posted_by    int             REFERENCES app_user,           -- NULL = posted by the system
  posted_at    timestamptz     NOT NULL DEFAULT now(),         -- the posting transaction's time
  expires_at   timestamptz,                                   -- hidden from boards afterwards
  withdrawn_at timestamptz,
  withdrawn_by int             REFERENCES app_user,
  CHECK (expires_at IS NULL OR expires_at > posted_at),
  CHECK ((withdrawn_at IS NULL) = (withdrawn_by IS NULL)),
  CHECK (withdrawn_at IS NULL OR withdrawn_at >= posted_at)
);
CREATE INDEX ON notice (posted_at DESC);
CREATE INDEX ON notice (posted_by);

CREATE TABLE notice_target (
  target_id     int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notice_id     int         NOT NULL REFERENCES notice ON DELETE CASCADE,
  role          user_role,
  dept_id       varchar(10) REFERENCES department,
  year_of_study smallint    CHECK (year_of_study BETWEEN 1 AND 4),
  division_id   int         REFERENCES division,
  -- year and division describe students only
  CHECK ((year_of_study IS NULL AND division_id IS NULL) OR role IS NOT DISTINCT FROM 'student'),
  -- a division already fixes the department and the year
  CHECK (division_id IS NULL OR (dept_id IS NULL AND year_of_study IS NULL)),
  UNIQUE NULLS NOT DISTINCT (notice_id, role, dept_id, year_of_study, division_id)
);
CREATE INDEX ON notice_target (notice_id);
CREATE INDEX ON notice_target (division_id);

CREATE TABLE notice_read (
  notice_id int         NOT NULL REFERENCES notice ON DELETE CASCADE,
  user_id   int         NOT NULL REFERENCES app_user ON DELETE CASCADE,
  read_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, notice_id)
);
CREATE INDEX ON notice_read (notice_id);

-- ---------------------------------------------------------------------------------------
-- Who each active account is, for audience matching: role, department, and (students) the
-- year and division they are in this session.
CREATE VIEW v_user_audience AS
SELECT u.user_id, u.role, COALESCE(p.dept_id, f.dept_id) AS dept_id, d.year_of_study, ss.division_id
FROM app_user u
LEFT JOIN student s ON s.student_id = u.student_id
LEFT JOIN program p ON p.program_id = s.program_id
LEFT JOIN faculty f ON f.faculty_id = u.faculty_id
LEFT JOIN student_section ss ON ss.student_id = u.student_id AND ss.academic_session_id = current_session_id()
LEFT JOIN division d ON d.division_id = ss.division_id
WHERE u.is_active;

-- Does this target describe this person?
CREATE FUNCTION notice_target_matches(t notice_target, a v_user_audience) RETURNS boolean
LANGUAGE sql IMMUTABLE AS $$
  SELECT (t.role IS NULL OR t.role = a.role)
     AND (t.dept_id IS NULL OR t.dept_id = a.dept_id)
     AND (t.year_of_study IS NULL OR t.year_of_study = a.year_of_study)
     AND (t.division_id IS NULL OR t.division_id = a.division_id)
$$;

-- Every live notice each user should see (filter by user_id), with whether they have read it.
-- Contract: v_user_notices(user_id) in docs/work-assignments.md.
CREATE VIEW v_user_notices AS
SELECT a.user_id, n.notice_id, n.title, n.body, n.category, n.is_important, n.posted_at, n.expires_at,
       n.posted_by, COALESCE(pp.display_name, 'Academic office') AS posted_by_name, pp.role AS posted_by_role,
       r.read_at, r.read_at IS NOT NULL AS is_read
FROM v_user_audience a
JOIN notice n ON n.withdrawn_at IS NULL AND (n.expires_at IS NULL OR n.expires_at > now())
             AND EXISTS (SELECT 1 FROM notice_target t WHERE t.notice_id = n.notice_id AND notice_target_matches(t, a))
LEFT JOIN v_user_profile pp ON pp.user_id = n.posted_by
LEFT JOIN notice_read r ON r.notice_id = n.notice_id AND r.user_id = a.user_id;

-- How many people a notice reaches and how many have read it (admin / poster report).
-- Matching depends only on (role, dept, year, division), so the ~50k accounts are grouped once
-- into a few hundred audience groups and the targets are matched against the groups.
CREATE VIEW v_notice_reach AS
WITH audience_group AS (
  SELECT role, dept_id, year_of_study, division_id, count(*)::int AS people
  FROM v_user_audience GROUP BY role, dept_id, year_of_study, division_id
)
SELECT n.notice_id,
       (SELECT COALESCE(sum(g.people), 0) FROM audience_group g
         WHERE EXISTS (SELECT 1 FROM notice_target t WHERE t.notice_id = n.notice_id
                         AND (t.role IS NULL OR t.role = g.role)
                         AND (t.dept_id IS NULL OR t.dept_id = g.dept_id)
                         AND (t.year_of_study IS NULL OR t.year_of_study = g.year_of_study)
                         AND (t.division_id IS NULL OR t.division_id = g.division_id)))::int AS recipients,
       (SELECT count(*) FROM notice_read r WHERE r.notice_id = n.notice_id)::int AS reads
FROM notice n;

-- ---------------------------------------------------------------------------------------
-- Posting rules on the notice itself: only admins, faculty or the system post; once posted,
-- only withdrawing is allowed (and it cannot be undone).
CREATE FUNCTION trg_notice_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.posted_by IS NOT NULL AND NOT EXISTS (
         SELECT 1 FROM app_user WHERE user_id = NEW.posted_by AND role IN ('admin', 'faculty') AND is_active) THEN
      RAISE EXCEPTION 'only the admin and faculty can post notices' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.withdrawn_at IS NOT NULL THEN
      RAISE EXCEPTION 'a new notice cannot be withdrawn already' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;

  IF OLD.withdrawn_at IS NOT NULL THEN
    RAISE EXCEPTION 'notice % has been withdrawn and cannot change', OLD.notice_id USING ERRCODE = 'check_violation';
  END IF;
  IF (NEW.title, NEW.body, NEW.category, NEW.is_important, NEW.posted_by, NEW.posted_at, NEW.expires_at)
     IS DISTINCT FROM (OLD.title, OLD.body, OLD.category, OLD.is_important, OLD.posted_by, OLD.posted_at, OLD.expires_at) THEN
    RAISE EXCEPTION 'a posted notice cannot be edited; withdraw it and post a new one' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.withdrawn_at IS NOT NULL THEN
    NEW.withdrawn_by := COALESCE(NEW.withdrawn_by, acting_user_id());
    -- the poster or an admin may withdraw
    IF NEW.withdrawn_by IS DISTINCT FROM OLD.posted_by AND NOT EXISTS (
         SELECT 1 FROM app_user WHERE user_id = NEW.withdrawn_by AND role = 'admin') THEN
      RAISE EXCEPTION 'only the poster or an admin can withdraw a notice' USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER guard BEFORE INSERT OR UPDATE ON notice FOR EACH ROW EXECUTE FUNCTION trg_notice_guard();

-- Audience rules: faculty may only address the students of divisions they teach this session.
-- Targets are fixed once the notice is posted (they may only be added in the posting transaction).
CREATE FUNCTION trg_notice_target_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  v_poster  int;
  v_role    user_role;
  v_faculty int;
  v_posted  timestamptz;
BEGIN
  -- deleting a whole notice cascades here after the notice row is gone; that is allowed
  IF TG_OP = 'DELETE' AND NOT EXISTS (SELECT 1 FROM notice WHERE notice_id = OLD.notice_id) THEN
    RETURN OLD;
  END IF;
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'the audience of a posted notice cannot be changed' USING ERRCODE = 'check_violation';
  END IF;
  SELECT n.posted_by, u.role, u.faculty_id, n.posted_at INTO v_poster, v_role, v_faculty, v_posted
  FROM notice n LEFT JOIN app_user u ON u.user_id = n.posted_by WHERE n.notice_id = NEW.notice_id;
  -- now() is fixed per transaction, so this holds only inside the transaction that posted it
  IF v_posted IS DISTINCT FROM now() THEN
    RAISE EXCEPTION 'the audience of a posted notice cannot be changed' USING ERRCODE = 'check_violation';
  END IF;
  -- year and division only describe students, so such a target is a student target
  IF NEW.year_of_study IS NOT NULL OR NEW.division_id IS NOT NULL THEN
    NEW.role := COALESCE(NEW.role, 'student');
  END IF;
  IF v_role = 'faculty' THEN
    IF NEW.division_id IS NULL OR NOT EXISTS (
         SELECT 1 FROM teaching_assignment ta
         WHERE ta.faculty_id = v_faculty AND ta.division_id = NEW.division_id
           AND ta.academic_session_id = current_session_id()) THEN
      RAISE EXCEPTION 'faculty can only post to divisions they teach this session' USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER audience_guard BEFORE INSERT OR UPDATE OR DELETE ON notice_target
  FOR EACH ROW EXECUTE FUNCTION trg_notice_target_guard();

-- Every notice must have an audience, checked when the posting transaction commits.
CREATE FUNCTION trg_notice_has_target() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM notice WHERE notice_id = NEW.notice_id)
     AND NOT EXISTS (SELECT 1 FROM notice_target WHERE notice_id = NEW.notice_id) THEN
    RAISE EXCEPTION 'notice % has no audience', NEW.notice_id USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER has_audience AFTER INSERT ON notice
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION trg_notice_has_target();

-- A user can only mark notices that were sent to them.
CREATE FUNCTION trg_notice_read_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM v_user_audience a JOIN notice_target t ON t.notice_id = NEW.notice_id
                 WHERE a.user_id = NEW.user_id AND notice_target_matches(t, a)) THEN
    RAISE EXCEPTION 'notice % was not sent to user %', NEW.notice_id, NEW.user_id USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER recipient_only BEFORE INSERT ON notice_read
  FOR EACH ROW EXECUTE FUNCTION trg_notice_read_guard();

-- ---------------------------------------------------------------------------------------
-- Contract for every team: post a notice with its audience in one call, returns the notice id.
-- p_targets is a JSON array of targets, each with any of role, dept_id, year_of_study, division_id;
-- '[{}]' is everyone. Examples:
--   SELECT erp.post_notice(NULL, 'Results published', 'Semester V results are out.', 'Exam',
--                          '[{"role": "student", "dept_id": "CSE", "year_of_study": 3}]');
--   SELECT erp.post_notice(42, 'Lab moved', 'Thursday lab is in A-204.', 'Academic', '[{"division_id": 17}]');
CREATE FUNCTION post_notice(p_posted_by int, p_title text, p_body text, p_category notice_category,
                            p_targets jsonb, p_is_important boolean DEFAULT false, p_expires_at timestamptz DEFAULT NULL)
RETURNS int
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE
  v_id int;
  t    jsonb;
BEGIN
  IF p_targets IS NULL OR jsonb_typeof(p_targets) <> 'array' OR jsonb_array_length(p_targets) = 0 THEN
    RAISE EXCEPTION 'a notice needs at least one audience target' USING ERRCODE = 'check_violation';
  END IF;
  INSERT INTO notice (title, body, category, is_important, posted_by, expires_at)
  VALUES (btrim(p_title), btrim(p_body), p_category, p_is_important, p_posted_by, p_expires_at)
  RETURNING notice_id INTO v_id;
  FOR t IN SELECT * FROM jsonb_array_elements(p_targets) LOOP
    INSERT INTO notice_target (notice_id, role, dept_id, year_of_study, division_id)
    VALUES (v_id, (t->>'role')::user_role, t->>'dept_id', (t->>'year_of_study')::smallint, (t->>'division_id')::int);
  END LOOP;
  RETURN v_id;
END $$;
