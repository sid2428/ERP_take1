-- T7 placement module. Uses only verified academic relations/views; CGPA/backlog assessment
-- remains explicitly unavailable until the examination workstream publishes its contract.
SET search_path = erp, public;

CREATE TYPE placement_drive_type AS ENUM ('FullTime', 'Internship');
CREATE TYPE placement_drive_status AS ENUM ('Draft', 'Open', 'Closed', 'Cancelled');
CREATE TYPE placement_application_status AS ENUM ('Applied', 'Shortlisted', 'Selected', 'Rejected', 'Withdrawn');
CREATE TYPE placement_round_status AS ENUM ('Planned', 'InProgress', 'Completed', 'Cancelled');
CREATE TYPE placement_round_result_status AS ENUM ('Pending', 'Passed', 'Failed', 'OnHold');
CREATE TYPE placement_offer_status AS ENUM ('Pending', 'Accepted', 'Declined', 'Withdrawn', 'Expired');

CREATE TABLE company (
  company_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_name varchar(140) NOT NULL,
  industry varchar(80), description text,
  website_url text CHECK (website_url IS NULL OR website_url ~ '^https?://'),
  contact_name varchar(100), contact_email varchar(120), contact_phone varchar(30), headquarters varchar(100),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX company_name_ci_uq ON company(lower(company_name));
CREATE TRIGGER touch BEFORE UPDATE ON company FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

CREATE TABLE placement_drive (
  drive_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id int NOT NULL REFERENCES company ON DELETE RESTRICT,
  title varchar(160) NOT NULL, role_title varchar(120) NOT NULL, drive_type placement_drive_type NOT NULL,
  description text NOT NULL DEFAULT '', job_location varchar(120),
  package_lpa numeric(8,2), stipend_monthly numeric(10,2),
  min_year smallint NOT NULL CHECK (min_year BETWEEN 1 AND 6),
  min_cgpa numeric(3,2) CHECK (min_cgpa BETWEEN 0 AND 10),
  max_active_backlogs smallint CHECK (max_active_backlogs >= 0),
  min_attendance_pct numeric(5,2) CHECK (min_attendance_pct BETWEEN 0 AND 100),
  opens_at timestamptz NOT NULL, deadline timestamptz NOT NULL, drive_date date,
  status placement_drive_status NOT NULL DEFAULT 'Draft',
  created_by int REFERENCES app_user, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (company_id, title),
  CHECK (deadline > opens_at),
  CHECK ((drive_type = 'FullTime' AND package_lpa IS NOT NULL AND package_lpa >= 0 AND stipend_monthly IS NULL)
      OR (drive_type = 'Internship' AND stipend_monthly IS NOT NULL AND stipend_monthly >= 0 AND package_lpa IS NULL))
);
CREATE INDEX placement_drive_status_deadline_idx ON placement_drive(status, deadline);
CREATE INDEX placement_drive_company_idx ON placement_drive(company_id, created_at DESC);
CREATE TRIGGER touch BEFORE UPDATE ON placement_drive FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

CREATE TABLE drive_program (
  drive_id int NOT NULL REFERENCES placement_drive ON DELETE CASCADE,
  program_id varchar(20) NOT NULL REFERENCES program ON DELETE RESTRICT,
  PRIMARY KEY (drive_id, program_id)
);
CREATE TABLE drive_round (
  round_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drive_id int NOT NULL REFERENCES placement_drive ON DELETE CASCADE,
  sequence_no smallint NOT NULL CHECK (sequence_no > 0),
  round_name varchar(100) NOT NULL, description text,
  scheduled_at timestamptz, status placement_round_status NOT NULL DEFAULT 'Planned',
  UNIQUE (drive_id, sequence_no), UNIQUE (round_id, drive_id)
);

CREATE TABLE student_placement_profile (
  student_id int PRIMARY KEY REFERENCES student ON DELETE CASCADE,
  skills text NOT NULL DEFAULT '' CHECK (length(skills) <= 2000),
  resume_url text CHECK (resume_url IS NULL OR resume_url ~ '^https?://'),
  linkedin_url text CHECK (linkedin_url IS NULL OR linkedin_url ~ '^https?://'),
  github_url text CHECK (github_url IS NULL OR github_url ~ '^https?://'),
  portfolio_url text CHECK (portfolio_url IS NULL OR portfolio_url ~ '^https?://'),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE placement_application (
  application_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id int NOT NULL REFERENCES student ON DELETE RESTRICT,
  drive_id int NOT NULL REFERENCES placement_drive ON DELETE RESTRICT,
  applied_at timestamptz NOT NULL DEFAULT now(),
  status placement_application_status NOT NULL DEFAULT 'Applied',
  withdrawn_at timestamptz, withdrawal_reason varchar(500), updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (student_id, drive_id), UNIQUE (application_id, drive_id),
  CHECK ((status = 'Withdrawn') = (withdrawn_at IS NOT NULL))
);
CREATE INDEX placement_application_drive_idx ON placement_application(drive_id, status, applied_at);
CREATE INDEX placement_application_student_idx ON placement_application(student_id, applied_at DESC);

CREATE TABLE round_result (
  result_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drive_id int NOT NULL REFERENCES placement_drive ON DELETE CASCADE,
  application_id int NOT NULL REFERENCES placement_application ON DELETE CASCADE,
  round_id int NOT NULL REFERENCES drive_round ON DELETE CASCADE,
  result placement_round_result_status NOT NULL DEFAULT 'Pending',
  result_at timestamptz NOT NULL DEFAULT now(), private_remarks varchar(1000),
  UNIQUE (application_id, round_id)
);
ALTER TABLE round_result ADD CONSTRAINT round_result_application_drive_fk
  FOREIGN KEY (application_id, drive_id) REFERENCES placement_application(application_id, drive_id) ON DELETE CASCADE;
ALTER TABLE round_result ADD CONSTRAINT round_result_round_drive_fk
  FOREIGN KEY (round_id, drive_id) REFERENCES drive_round(round_id, drive_id) ON DELETE CASCADE;

CREATE TABLE placement_offer (
  offer_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id int NOT NULL UNIQUE REFERENCES placement_application ON DELETE RESTRICT,
  package_lpa numeric(8,2), stipend_monthly numeric(10,2),
  offered_at timestamptz NOT NULL DEFAULT now(), response_deadline timestamptz NOT NULL,
  joining_date date, status placement_offer_status NOT NULL DEFAULT 'Pending', responded_at timestamptz,
  CHECK ((package_lpa IS NOT NULL AND package_lpa >= 0 AND stipend_monthly IS NULL)
      OR (package_lpa IS NULL AND stipend_monthly IS NOT NULL AND stipend_monthly >= 0)),
  CHECK ((status IN ('Accepted','Declined') AND responded_at IS NOT NULL) OR status NOT IN ('Accepted','Declined'))
);
CREATE INDEX placement_offer_response_idx ON placement_offer(status, response_deadline);

-- Student year derives from verified current student_section/division data.
-- CGPA and backlog criteria fail closed until the examination module publishes its view.
CREATE FUNCTION is_eligible(p_student_id int, p_drive_id int)
RETURNS TABLE(eligible boolean, reasons text[], assessment_pending boolean)
LANGUAGE sql STABLE SET search_path = erp, public AS $$
  WITH facts AS (
    SELECT d.*, s.program_id, s.status AS student_status, p.dept_id AS student_dept,
           div.year_of_study,
           EXISTS (SELECT 1 FROM drive_program dp WHERE dp.drive_id=d.drive_id) AS has_program_filter,
           EXISTS (SELECT 1 FROM drive_program dp WHERE dp.drive_id=d.drive_id AND dp.program_id=s.program_id) AS program_match,
           (SELECT round(avg(a.attendance_pct),2) FROM v_student_attendance_by_course a
             WHERE a.student_id=p_student_id AND a.academic_session_id=current_session_id()) AS attendance_pct,
           EXISTS (SELECT 1 FROM placement_offer o JOIN placement_application a USING(application_id)
             JOIN placement_drive od USING(drive_id)
             WHERE a.student_id=p_student_id AND od.drive_type='FullTime' AND o.status='Accepted') AS has_accepted_fulltime,
           (SELECT max(o.package_lpa) FROM placement_offer o JOIN placement_application a USING(application_id)
             JOIN placement_drive od USING(drive_id)
             WHERE a.student_id=p_student_id AND od.drive_type='FullTime' AND o.status='Accepted') AS accepted_package
      FROM placement_drive d CROSS JOIN student s
      LEFT JOIN program p ON p.program_id=s.program_id
      LEFT JOIN student_section ss ON ss.student_id=s.student_id AND ss.academic_session_id=current_session_id()
      LEFT JOIN division div ON div.division_id=ss.division_id
     WHERE s.student_id=p_student_id AND d.drive_id=p_drive_id
  ), checked AS (
    SELECT f.*,
      array_remove(ARRAY[
        CASE WHEN status <> 'Open' THEN 'This drive is not open' END,
        CASE WHEN student_status <> 'Active' THEN 'Only active students may apply' END,
        CASE WHEN now() < opens_at THEN 'Applications have not opened' END,
        CASE WHEN now() >= deadline THEN 'The application deadline has passed' END,
        CASE WHEN year_of_study IS NULL THEN 'Current academic year is unavailable' WHEN year_of_study < min_year THEN 'Your year of study does not meet this drive''s requirement' END,
        CASE WHEN has_program_filter AND NOT program_match THEN 'Your program is not eligible for this drive' END,
        CASE WHEN min_cgpa IS NOT NULL THEN 'CGPA assessment is unavailable' END,
        CASE WHEN max_active_backlogs IS NOT NULL THEN 'Backlog assessment is unavailable' END,
        CASE WHEN min_attendance_pct IS NOT NULL AND attendance_pct IS NULL THEN 'Attendance assessment is unavailable' WHEN min_attendance_pct IS NOT NULL AND attendance_pct < min_attendance_pct THEN 'Minimum attendance requirement is not met' END,
        CASE WHEN has_accepted_fulltime AND (drive_type <> 'FullTime' OR package_lpa < accepted_package * 1.5) THEN 'An accepted full-time offer restricts applications to full-time drives paying at least 1.5x that package' END
      ]::text[], NULL) AS failed,
      (min_cgpa IS NOT NULL OR max_active_backlogs IS NOT NULL) AS pending
    FROM facts f
  )
  SELECT cardinality(failed)=0, failed, pending FROM checked
$$;

CREATE FUNCTION placement_application_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE e record; d placement_drive; accepted numeric;
BEGIN
  IF TG_OP='INSERT' OR NEW.student_id IS DISTINCT FROM OLD.student_id OR NEW.drive_id IS DISTINCT FROM OLD.drive_id THEN
    PERFORM pg_advisory_xact_lock(NEW.student_id);
    SELECT * INTO e FROM is_eligible(NEW.student_id, NEW.drive_id);
    IF NOT COALESCE(e.eligible,false) THEN
      RAISE EXCEPTION 'application is not eligible: %', array_to_string(COALESCE(e.reasons,ARRAY['unknown student or drive']),'; ')
        USING ERRCODE='check_violation';
    END IF;
    SELECT * INTO d FROM placement_drive WHERE drive_id=NEW.drive_id;
    IF d.drive_type='FullTime' THEN
      SELECT max(o.package_lpa) INTO accepted FROM placement_offer o
        JOIN placement_application a USING(application_id) JOIN placement_drive od USING(drive_id)
       WHERE a.student_id=NEW.student_id AND od.drive_type='FullTime' AND o.status='Accepted';
      IF accepted IS NOT NULL AND d.package_lpa < accepted*1.5 THEN
        RAISE EXCEPTION 'drive package is below the 1.5x accepted offer threshold' USING ERRCODE='check_violation';
      END IF;
    END IF;
  END IF;
  IF TG_OP='UPDATE' AND NEW.status IS DISTINCT FROM OLD.status AND NOT (
      (OLD.status='Applied' AND NEW.status IN ('Shortlisted','Rejected','Withdrawn')) OR
      (OLD.status='Shortlisted' AND NEW.status IN ('Selected','Rejected','Withdrawn')) OR
      (OLD.status='Selected' AND NEW.status IN ('Rejected','Withdrawn')) ) THEN
    RAISE EXCEPTION 'invalid application status transition' USING ERRCODE='check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER placement_application_guard BEFORE INSERT OR UPDATE ON placement_application
  FOR EACH ROW EXECUTE FUNCTION placement_application_guard();

CREATE FUNCTION placement_offer_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = erp, public AS $$
DECLARE student_key int; app_status placement_application_status; drive_kind placement_drive_type;
BEGIN
  SELECT a.student_id,a.status,d.drive_type INTO student_key,app_status,drive_kind
    FROM placement_application a JOIN placement_drive d USING(drive_id) WHERE a.application_id=NEW.application_id FOR UPDATE OF a;
  IF app_status <> 'Selected' THEN RAISE EXCEPTION 'offer requires a selected application' USING ERRCODE='check_violation'; END IF;
  IF (drive_kind='FullTime' AND (NEW.package_lpa IS NULL OR NEW.stipend_monthly IS NOT NULL)) OR
     (drive_kind='Internship' AND (NEW.stipend_monthly IS NULL OR NEW.package_lpa IS NOT NULL)) THEN
    RAISE EXCEPTION 'offer compensation must match the drive type' USING ERRCODE='check_violation';
  END IF;
  PERFORM pg_advisory_xact_lock(student_key);
  IF TG_OP='UPDATE' AND NEW.status IS DISTINCT FROM OLD.status AND NOT (OLD.status='Pending' AND NEW.status IN ('Accepted','Declined','Withdrawn','Expired')) THEN
    RAISE EXCEPTION 'invalid offer status transition' USING ERRCODE='check_violation';
  END IF;
  IF NEW.status='Accepted' AND drive_kind='FullTime' AND EXISTS (
    SELECT 1 FROM placement_offer o JOIN placement_application a USING(application_id)
      JOIN placement_drive d USING(drive_id)
     WHERE a.student_id=student_key AND d.drive_type='FullTime' AND o.status='Accepted' AND o.offer_id<>NEW.offer_id
  ) THEN RAISE EXCEPTION 'student already has an accepted full-time offer' USING ERRCODE='check_violation'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER placement_offer_guard BEFORE INSERT OR UPDATE ON placement_offer
  FOR EACH ROW EXECUTE FUNCTION placement_offer_guard();

CREATE FUNCTION respond_placement_offer(p_offer_id int, p_student_id int, p_accept boolean)
RETURNS void LANGUAGE plpgsql SET search_path = erp, public AS $$
BEGIN
  UPDATE placement_offer o SET status=CASE WHEN p_accept THEN 'Accepted'::placement_offer_status ELSE 'Declined'::placement_offer_status END,
         responded_at=now()
    FROM placement_application a
   WHERE o.offer_id=p_offer_id AND o.application_id=a.application_id AND a.student_id=p_student_id
     AND o.status='Pending' AND now()<o.response_deadline;
  IF NOT FOUND THEN RAISE EXCEPTION 'offer is unavailable or response deadline has passed' USING ERRCODE='check_violation'; END IF;
END $$;

CREATE VIEW v_student_placement_status AS
SELECT s.student_id,
       count(DISTINCT a.application_id) FILTER (WHERE a.status <> 'Withdrawn')::int AS applications,
       count(DISTINCT o.offer_id)::int AS offers,
       max(o.package_lpa) FILTER (WHERE d.drive_type='FullTime' AND o.status='Accepted') AS best_offer_lpa,
       COALESCE(bool_or(d.drive_type='FullTime' AND o.status='Accepted'),false) AS is_placed
  FROM student s
  LEFT JOIN placement_application a ON a.student_id=s.student_id
  LEFT JOIN placement_drive d ON d.drive_id=a.drive_id
  LEFT JOIN placement_offer o ON o.application_id=a.application_id
 GROUP BY s.student_id;

